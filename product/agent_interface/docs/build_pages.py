#!/usr/bin/env python3
"""Generate one documentation page per `vp` command family: docs/FAMILY_<noun>.md.

Inputs (read-only): design/MCP_TOOLS.json (the frozen command table, lane ops-design), router/seeds.jsonl (facts
pinned to source lines) and docs/family_notes.json (hand-written purpose, sequence and traps per family).
Output is deterministic: no timestamps. Run, then `vp docs build`:
    python3 -I product/agent_interface/docs/build_pages.py && python3 -I product/agent_interface/router/vp_docs.py build
"""
import json
import os
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
AI = HERE.parent
TOOLS = [AI / 'design' / 'MCP_TOOLS.json', Path(os.environ.get('VP_OPS_ROOT') or AI.parents[2]) / 'vp-wt-fable-ai1' / 'product' / 'agent_interface' / 'design' / 'MCP_TOOLS.json']
CLASSES = {'R': 'read-only', 'W': 'write-own', 'X': 'starts a process', 'H': 'human-facing', 'D': 'destructive, needs `--confirm`'}
# seed family -> command families whose page lists the fact
SEED_TO_FAMILY = {'capsule': ['capsule'], 'mcp': ['browser', 'identity'], 'engine': ['engine'], 'rewind': ['rewind'], 'blender': ['blender'],
                  'record': ['record'], 'vision': ['vision'], 'room': ['room'], 'swarm': ['agents'], 'tasklight': ['tasklight'],
                  'newton': ['out'], 'queue': ['queue'], 'agents': ['agents'], 'overlay': ['record'], 'projection': ['projection'],
                  'auction': ['queue'], 'troubleshooting': []}


def main():
    src = next((p for p in TOOLS if p.is_file()), None)
    if src is None:
        print('MCP_TOOLS.json not found; family pages not generated', file=sys.stderr)
        return 8
    spec = json.loads(src.read_text(encoding='utf-8'))
    notes = json.loads((HERE / 'family_notes.json').read_text(encoding='utf-8'))
    seeds = [json.loads(l) for l in (AI / 'router' / 'seeds.jsonl').read_text(encoding='utf-8').splitlines() if l.strip()]
    codes = spec.get('codes', {})
    families = {}
    for tool in spec['tools']:
        families.setdefault(tool['argv'][0], []).append(tool)
    for old in HERE.glob('FAMILY_*.md'):
        old.unlink()
    for fam, tools in families.items():
        note = notes.get(fam, {})
        out = [f"# `vp {fam}`: {note.get('title', fam)}", '', note.get('purpose', ''), '',
               f"Generated by `docs/build_pages.py` from `design/MCP_TOOLS.json` ({spec.get('schema')}), `docs/family_notes.json` and "
               "`router/seeds.jsonl`. For exact file:line citations with freshness marks run `vp docs ask \"<question>\"`.", '',
               '## Commands', '', '| Command | Class | What it does | Wraps |', '|---|---|---|---|']
        for t in tools:
            desc = t['description'].split('] ', 1)[-1]
            out.append(f"| `vp {' '.join(t['argv'])}` | {t['safety']} ({CLASSES.get(t['safety'], '')}) | {desc} | `{t['wraps'].replace('|', '/')}` |")
        out += ['', '## Arguments, confirm ids and codes', '']
        for t in tools:
            props, req = t['inputSchema']['properties'], set(t['inputSchema'].get('required', []))
            pos = [f'<{p}>' for p in t['positional']]
            flags = []
            for k, v in props.items():
                if k in t['positional'] or k in ('dry_run', 'timeout_s', 'confirm'):
                    continue
                flag = '--' + k.replace('_', '-')
                flags.append(flag if k in req else f'[{flag}]')
            line = f"- `vp {' '.join(t['argv'] + pos + flags)}`"
            if 'confirm' in props:
                line += f" `--confirm <id>`: {props['confirm']['description']}."
            line += f" MCP tool `{t['name']}` (tier {t['tier']}). Codes: " + ', '.join(f"`{c}` rc {codes.get(c, '?')}" for c in t['codes']) + '.'
            out.append(line)
            for k, v in props.items():
                if k not in ('dry_run', 'timeout_s', 'confirm') and v.get('description'):
                    out.append(f"  - `{'<' + k + '>' if k in t['positional'] else '--' + k.replace('_', '-')}` ({v.get('type', 'string')}{', required' if k in req else ''}): {v['description']}")
        out += ['', 'Every command also accepts `--dry-run` (code `DRY_RUN`, nothing starts) and `--timeout-s S` (code `TIMEOUT`, rc 124).', '']
        if note.get('sequence'):
            out += ['## Typical sequence', '', '```sh'] + note['sequence'] + ['```', '']
        if note.get('rules'):
            out += ['## Rules and traps', ''] + [f'- {r}' for r in note['rules']] + ['']
        facts = [s for s in seeds if fam in SEED_TO_FAMILY.get(s['family'], []) and (fam != 'identity' or 'identity' in s['text'].lower())
                 and (fam != 'browser' or 'vp_identity' not in s['text'])]
        if facts:
            out += ['## Facts from the wrapped tools', '', 'Each fact is pinned to a source line; `vp docs ask` returns the line and whether it is still FRESH.', '']
            out += [f"- ({s['kind']}) {s['text']} Source: `{s['path']}`." for s in facts] + ['']
        (HERE / f'FAMILY_{fam}.md').write_text('\n'.join(out), encoding='utf-8')
    print(f'{len(families)} family pages written from {src}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
