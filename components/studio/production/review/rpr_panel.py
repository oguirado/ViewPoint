def build_card(pack, root, slot, nonce, version=1):
    data = card_inputs(pack, root, slot, nonce)
    protocol, manifest, manifest_sha = data["protocol"], data["manifest"], data["manifest_sha"]
    info = data["info"]
    if version >= 2:
        ctx, clips = None, None
        limit = protocol["context_max_bytes"] - protocol["card"].get("fit_margin_bytes", 0)
        for candidate in CARD_LADDER:
            text = render_card_v2(data, candidate)
            if len(text.encode("utf-8")) + len(CARD_TASK) <= limit:
                ctx, clips = text, candidate
                break
        if ctx is None:
            raise C.Harness(f"card context {slot}: even empty accounts do not fit {limit} bytes")
        meta_extra = {"context_version": 2, "clips": list(clips)}
    else:
        ctx = render_card_v1(data)
        meta_extra = {}
    meta = {"kind": "card", "protocol": C.VERSION, "pack": str(Path(pack).resolve()), "slot": slot,
            "seat": info["seat"], "card_token": info["card_token"], "brief_nonce": nonce, "blind_sha256": data["blind_sha"],
            "ctx_sha256": C.sha_text(ctx), "task_sha256": C.sha_text(CARD_TASK),
            "movie_sha256": manifest["movie"]["sha256"], "manifest_sha256": manifest_sha,
            **check_budget(ctx, CARD_TASK, protocol, f"card context {slot}"), **meta_extra}
    return ctx, CARD_TASK, meta


def card_version(meta):
    return meta.get("context_version", 1)


def ensure_card_context(pack, root, slot):
    stored = card_dir(root, pack, slot) / "ctx.json"
    if stored.is_file():
        return C.read_json(stored)
    nonce = secrets.token_hex(8)
    ctx, task, meta = build_card(pack, root, slot, nonce, C.load_protocol()["card"].get("context_version", 1))
    directory = card_dir(root, pack, slot)
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "ctx.md").write_text(ctx, encoding="utf-8")
    (directory / "task.md").write_text(task, encoding="utf-8")
    C.write_json(stored, meta, readonly=True)
    return meta


def regenerate_card(pack, root, slot, meta):
    directory = card_dir(root, pack, slot)
    ctx, task, rebuilt = build_card(pack, root, slot, meta["brief_nonce"], card_version(meta))
    on_disk = (directory / "ctx.md").read_text(encoding="utf-8") if (directory / "ctx.md").is_file() else ""
    if rebuilt != meta or C.sha_text(on_disk) != meta["ctx_sha256"] or C.sha_text(task) != meta["task_sha256"]:
        raise C.Refused("modified_card_context", "the scoring card was shown a context that differs from the sealed one",
                        next_command("card-ctx", "--pack", pack))
    return ctx


def parse_card(response, manifest, info, meta):
    refuse = next_command("accept", "--pack", meta["pack"], "--slot", meta["slot"])
    keys = CARD_KEYS if card_version(meta) >= 2 else CARD_KEYS_V1
    if not isinstance(response, dict) or set(response) != keys:
        if isinstance(response, dict) and "blind_action_match" in response and card_version(meta) >= 2:
            raise C.Refused("response_shape", "a scoring card does not report whether the account matches the action; "
                            "the orchestrator compares the sealed account itself", refuse)
        raise C.Refused("response_shape", f"a scoring card has exactly the keys {sorted(keys)}", refuse)
    if response["card_token"] != info["card_token"]:
        raise C.Refused("copied_card", "a scoring card carries the token issued to its own viewer", refuse)
    if response["blind_sha256"] != meta["blind_sha256"]:
        raise C.Refused("copied_card", "a scoring card is bound to its own viewer's sealed account", refuse)
    if response["brief_nonce"] != meta["brief_nonce"]:
        raise C.Refused("stale_card_brief", "the scoring card answers another release of the rubric", refuse)
    if (response["movie_sha256"], response["manifest_sha256"]) != (meta["movie_sha256"], meta["manifest_sha256"]):
        raise C.Refused("card_binding_mismatch", "the scoring card names another movie or manifest", refuse)
    if response["catalog_sha256"] != manifest["catalog_sha256"]:
        raise C.Refused("stale_pts", "the scoring card is bound to another timing catalog", refuse)
    claimed = None
    try:
        pixel_access = response["pixel_access"]
        if not isinstance(pixel_access, bool):
            raise ValueError("pixel_access is true or false")
        if card_version(meta) < 2 and not isinstance(response["blind_action_match"], bool):
            raise ValueError("blind_action_match is true or false")
        claimed = response["blind_action_match"] if card_version(meta) < 2 else None
        if not isinstance(response["summary"], str) or not response["summary"].strip():
            raise ValueError("summary is missing")
        scores = response["scores"]
        if not isinstance(scores, dict) or set(scores) != set(C.AXES):
            raise ValueError(f"scores has exactly the keys {list(C.AXES)}")
        tokens = token_map(manifest)
        parsed = {}
        for axis in C.AXES:
            entry = scores[axis]
            if not isinstance(entry, dict) or set(entry) != {"score", "evidence"}:
                raise ValueError(f"{axis}: each axis has score and evidence")
            score = to_int(entry["score"])
            if not 1 <= score <= 10:
                raise ValueError(f"{axis}: score is a whole number from 1 to 10")
            parsed[axis] = {"score": score, "evidence": parse_evidence(entry["evidence"], set(tokens), tokens, axis, refuse)}
        if not isinstance(response["defects"], list):
            raise ValueError("defects must be a list")
        defects = []
        for defect in response["defects"]:
            if not isinstance(defect, dict) or not isinstance(defect.get("what"), str) or not defect["what"].strip():
                raise ValueError("each defect needs a description")
            index, severity = to_int(defect.get("index")), str(defect.get("severity", "")).strip().upper()
            if index not in tokens:
                raise C.Refused("evidence_mismatch", f"defect frame {index} is not a listed frame", refuse)
            if severity not in SEVERITY:
                raise ValueError("defect severity is MAJOR or MINOR")
            defects.append({"severity": severity, "index": index, "what": defect["what"].strip()})
    except ValueError as exc:
        raise C.Refused("response_shape", f"the scoring card is malformed: {exc}", refuse) from exc
    minimum = C.load_protocol()["blind"]["min_evidence"]
    if pixel_access and any(len(entry["evidence"]) < minimum for entry in parsed.values()):
        raise C.Refused("evidence_missing", "every axis cites at least one listed frame", refuse)
    card = {"card_token": info["card_token"], "brief_nonce": meta["brief_nonce"], "blind_sha256": meta["blind_sha256"],
            "movie_sha256": meta["movie_sha256"], "manifest_sha256": meta["manifest_sha256"],
            "catalog_sha256": manifest["catalog_sha256"], "pixel_access": pixel_access,
            "scores": parsed, "defects": defects, "summary": response["summary"].strip()}
    if card_version(meta) < 2:
        # Kept because it is part of the sealed bytes of a first-layout card. It is never a verdict input.
        card["blind_action_match"] = claimed
    return card


def card_fingerprint(card):
    return C.sha_bytes(C.json_bytes({"scores": card["scores"], "defects": card["defects"],
                                     "summary": card["summary"]}))


def accept(pack, root, slot, oneshot_path, ledger=None):
    """Accept a scoring card only if it is bound to this viewer's sealed account and this release."""
    pack, root = Path(pack), as_root(root)
    protocol = C.load_protocol()
    meta = ensure_card_context(pack, root, slot)
    regenerate_card(pack, root, slot, meta)
    R.verify(pack, pixels=False)
    manifest, manifest_sha = R.load_manifest(pack)
    viewers = load_viewers(root, pack)
    info = viewers["slots"][slot]
    directory = card_dir(root, pack, slot)
    response, common = observer_record(C.read_json(oneshot_path), meta, manifest, manifest_sha, directory,
                                       oneshot_path, protocol, ledger)
    offered = response.get("blind_sha256") if isinstance(response, dict) else None
    for other in viewers["slots"]:
        if other != slot and offered == blind_digest(load_seals(pack, root, other)[0]):
            raise C.Refused("copied_card", "this scoring card carries the sealed account of another viewer",
                            observe_command(pack, slot, "card"))
    card = parse_card(response, manifest, info, meta)
    record = {**common, "card_token": info["card_token"], "blind_sha256": meta["blind_sha256"],
              "card_sha256": C.sha_bytes(C.json_bytes(card)), "fingerprint": card_fingerprint(card),
              "cannot_see": not card["pixel_access"]}
    if (directory / "accept.json").is_file():
        old = C.read_json(directory / "accept.json")
        if old["card_sha256"] != record["card_sha256"]:
            raise C.Refused("already_sealed", "a scoring card is accepted once; a different card needs a new viewer slot",
                            next_command("score", "--pack", pack))
        return {"status": "ACCEPTED", **record, "unchanged": True}
    C.write_json(directory / "card.json", card, readonly=True)
    C.write_json(directory / "accept.json", record, readonly=True)
    append_seal(root, pack, record)
    return {"status": "ACCEPTED", **record}


# ------------------------------------------------------------------ stage 3: the judge
def build_match(pack, root, slot, nonce):
    """The context of the independent judge: the intended action and one viewer's sealed account, nothing else."""
    protocol = C.load_protocol()
    manifest, manifest_sha = R.load_manifest(pack)
    seals, missing = load_seals(pack, root, slot)
    if missing is not None:
        raise C.Refused("unsealed_blind", f"segment {missing} of this viewer has no sealed first viewing; nothing is judged",
                        observe_command(pack, slot, "blind", missing))
    brief = load_brief(pack, root)
    if not brief or not brief.get("contract"):
        raise C.Refused("action_contract_unbound", "bind the intended action and its contract before any viewing of this pack",
                        next_command("brief", "--pack", pack))
    elements = A.compile_contract(brief["contract"])
    blind_sha = blind_digest(seals)
    token = A.judge_token(manifest["movie"]["sha256"], manifest_sha, slot, blind_sha, nonce)
    seat = protocol["seats"]["judge"]["seat"]
    accounts = []
    for record, response in seals:
        bounds = response["segment"]
        accounts.append(
            f"### Segment {record['segment'] + 1}, frames {bounds['first_index']}–{bounds['last_index']}, "
            f"response SHA-256 `{record['response_sha256']}`\n\n"
            f"- pixel_access: {str(response['pixel_access']).lower()}; frames_opened: {response['frames_opened']} of {bounds['count']}\n"
            f"- account: {response['account']}\n"
            + "".join(f"- event ({e['first_index']}–{e['last_index']}, {e['confidence']}): {e['description']}\n" for e in response["events"])
            + "".join(f"- frame {e['index']}: {e['observation']}\n" for e in response["evidence"])
            + "".join(f"- unclear: {line}\n" for line in response["unclear"]) + "\n")
    listed = ", ".join(f"`{element['id']}`" for element in elements)
    ctx = f"""# Action match · first viewing of {slot}

An independent first viewer watched a movie in {len(seals)} segments without being told anything about it. Its sealed account is reproduced below exactly as it was returned, before anything was disclosed to it. You are now given the intended action of the movie. Compare the two.

Movie SHA-256 `{manifest['movie']['sha256']}`, manifest SHA-256 `{manifest_sha}`, sealed account SHA-256 `{blind_sha}`.

## Intended action, from the production plan

{brief['text']}

## What to decide

For each element below, say whether the viewer's sealed account names it, and quote the words that name it.

{chr(10).join(f"- {element['id']}: {element['label']}" + ("" if element["required"] else " (optional)") for element in elements)}

1. `named` is true only if the account itself states the element as something that happens in the movie. A denial ("does not touch", "nothing changes"), a statement that something stays as it was, a question, or a line listed under `unclear` does not name it.
2. `quote` is copied character for character from one field of one segment: its account, one of its event descriptions, or one of its evidence observations. No paraphrase, no ellipsis. When `named` is false, quote the words that come closest, or give an empty string.
3. `order_ok` is true when the account places the stop or plant no later than the contact, and the consequence after the contact, by the frame indices it cites or by the order of the account.
4. Judge only what the sealed account says. Do not infer from the intended action what the viewer must have seen.

## Sealed account

{chr(10).join(accounts)}
## Response

Return ONE JSON object and nothing else, with exactly these keys:

- `judge_token`: "{token}"
- `brief_nonce`: "{nonce}"
- `blind_sha256`: "{blind_sha}"
- `movie_sha256`: "{manifest['movie']['sha256']}"
- `manifest_sha256`: "{manifest_sha}"
- `viewer_slot`: "{slot}"
- `elements`: an object with exactly the keys {listed}; each is {{"named": true | false, "quote": str, "segment": int, "field": "account" | "events" | "evidence"}}.
- `order_ok`: true or false.
- `summary`: 1–3 sentences.
"""
    meta = {"kind": "match", "protocol": C.VERSION, "pack": str(Path(pack).resolve()), "slot": slot,
            "seat": seat, "judge_token": token, "brief_nonce": nonce, "blind_sha256": blind_sha,
            "ctx_sha256": C.sha_text(ctx), "task_sha256": C.sha_text(MATCH_TASK),
            "movie_sha256": manifest["movie"]["sha256"], "manifest_sha256": manifest_sha,
            **check_budget(ctx, MATCH_TASK, protocol, f"judge context {slot}", protocol["judge"]["context_max_bytes"])}
    return ctx, MATCH_TASK, meta


def ensure_match_context(pack, root, slot):
    stored = match_dir(root, pack, slot) / "ctx.json"
    if stored.is_file():
        return C.read_json(stored)
    nonce = secrets.token_hex(8)
    ctx, task, meta = build_match(pack, root, slot, nonce)
    directory = match_dir(root, pack, slot)
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "ctx.md").write_text(ctx, encoding="utf-8")
    (directory / "task.md").write_text(task, encoding="utf-8")
    C.write_json(stored, meta, readonly=True)
    return meta


def regenerate_match(pack, root, slot, meta):
    directory = match_dir(root, pack, slot)
    ctx, task, rebuilt = build_match(pack, root, slot, meta["brief_nonce"])
    on_disk = (directory / "ctx.md").read_text(encoding="utf-8") if (directory / "ctx.md").is_file() else ""
    if rebuilt != meta or C.sha_text(on_disk) != meta["ctx_sha256"] or C.sha_text(task) != meta["task_sha256"]:
        raise C.Refused("modified_match_context", "the judge was shown a context that differs from the sealed one",
                        next_command("judge", "--pack", pack, "--slot", slot))
    return ctx


def parse_judgment(response, seals, contract, meta, refuse):
    if not isinstance(response, dict) or set(response) != JUDGMENT_KEYS:
        raise C.Refused("judgment_shape", f"a judgment has exactly the keys {sorted(JUDGMENT_KEYS)}", refuse)
    binding = (response["judge_token"], response["brief_nonce"], response["blind_sha256"], response["movie_sha256"],
               response["manifest_sha256"], response["viewer_slot"])
    if binding != (meta["judge_token"], meta["brief_nonce"], meta["blind_sha256"], meta["movie_sha256"],
                   meta["manifest_sha256"], meta["slot"]):
        raise C.Refused("response_binding_mismatch",
                        "the judgment does not echo the judge token, nonce, digests and viewer slot of its sealed context", refuse)
    if not isinstance(response["summary"], str) or not response["summary"].strip():
        raise C.Refused("judgment_shape", "a judgment carries a summary", refuse)
    judgment = {"judge_token": meta["judge_token"], "brief_nonce": meta["brief_nonce"], "blind_sha256": meta["blind_sha256"],
                "movie_sha256": meta["movie_sha256"], "manifest_sha256": meta["manifest_sha256"], "viewer_slot": meta["slot"],
                "elements": response["elements"], "order_ok": response["order_ok"], "summary": response["summary"].strip()}
    # Every quotation is checked against the sealed account here; a judgment that does not hold is refused.
    A.verify_judgment(judgment, seals, contract, refuse)
    return judgment


def judge(pack, root, slot, oneshot_path, ledger=None):
    """Accept the judgment of an independent seat over one viewer's sealed account."""
    pack, root = Path(pack), as_root(root)
    protocol = C.load_protocol()
    meta = ensure_match_context(pack, root, slot)
    regenerate_match(pack, root, slot, meta)
    R.verify(pack, pixels=False)
    manifest, manifest_sha = R.load_manifest(pack)
    seals, missing = load_seals(pack, root, slot)
    if missing is not None:
        raise C.Refused("unsealed_blind", "a seal of this viewer went missing; nothing is judged", next_command("score", "--pack", pack))
    directory = match_dir(root, pack, slot)
    response, common = observer_record(C.read_json(oneshot_path), meta, manifest, manifest_sha, directory,
                                       oneshot_path, protocol, ledger)
    judgment = parse_judgment(response, seals, A.compile_contract(load_brief(pack, root)["contract"]), meta,
                              next_command("judge", "--pack", pack, "--slot", slot))
    record = {**common, "judge_token": meta["judge_token"], "blind_sha256": meta["blind_sha256"],
              "judgment_sha256": C.sha_bytes(C.json_bytes(judgment))}
    if (directory / "accept.json").is_file():
        old = C.read_json(directory / "accept.json")
        if old["judgment_sha256"] != record["judgment_sha256"]:
            raise C.Refused("already_sealed", "a judgment is accepted once; another judgment needs its own release",
                            next_command("score", "--pack", pack))
        return {"status": "JUDGED", **record, "unchanged": True}
    C.write_json(directory / "judgment.json", judgment, readonly=True)
    C.write_json(directory / "accept.json", record, readonly=True)
    append_seal(root, pack, record)
    return {"status": "JUDGED", **record}


# ------------------------------------------------------------------ verdict
def evaluate(card):
    thresholds = C.load_protocol()["thresholds"]
    scores = {axis: card["scores"][axis]["score"] for axis in C.AXES}
    subtotal = sum(scores[axis] for axis in C.AXES[:-1])
    reasons = []
    if min(scores.values()) < thresholds["min_axis"]:
        reasons.append("axis_below_8")
    if subtotal < thresholds["first_four_subtotal"]:
        reasons.append("first_four_below_34")
    if sum(scores.values()) < thresholds["total"]:
        reasons.append("total_below_43")
    if reasons:
        reasons.insert(0, "rubric_threshold")
    if any(defect["severity"] == "MAJOR" for defect in card["defects"]):
        reasons.append("major_defect_veto")
    if not card["pixel_access"]:
        reasons.append("cannot_see")
    return {"scores": scores, "first_four_subtotal": subtotal, "total": sum(scores.values()),
            "pass": not reasons, "reasons": reasons,
            "major_defects": sum(defect["severity"] == "MAJOR" for defect in card["defects"]),
            "minor_defects": sum(defect["severity"] == "MINOR" for defect in card["defects"])}


def slot_evidence(pack, root, slot, manifest, manifest_sha, protocol, ledger=None):
    """Read every seal and the card of one slot again. Each must still verify against its own context."""
    segments = len(plan_segments(manifest, protocol))
    seals, missing = load_seals(pack, root, slot)
    problems, valid, kinds = [], [], []
    for number, (record, response) in enumerate(seals):
        directory = blind_dir(root, pack, slot, number)
        try:
            meta = C.read_json(directory / "ctx.json")
            regenerate_blind(pack, root, slot, meta)
            if C.sha_bytes(C.json_bytes(response)) != record["response_sha256"]:
                raise C.Refused("seal_response_changed", "the sealed response differs from the hash recorded at the seal",
                                next_command("score", "--pack", pack))
            attestation = X.recheck(record, meta, directory, protocol, ledger, observe_command(pack, slot, "blind", number))
        except (C.Refused, C.Harness) as exc:
            problems.append(f"seal_invalid:{number}:{getattr(exc, 'reason', 'harness_error')}")
            break  # the account is no longer one chain: what follows is kept on record only
        valid.append((record, response))
        kinds.append(attestation["kind"])
    complete = missing is None and len(valid) == segments and not problems
    evidence = {"segments": segments, "seals": len(valid), "seals_on_record": len(seals), "complete": complete,
                "problems": problems, "card": None, "attested": bool(valid) and kinds == ["swarm"] * len(kinds),
                "observer": ("swarm" if set(kinds) == {"swarm"} else "scripted" if set(kinds) == {"scripted"} else
                             "mixed" if kinds else "none")}
    directory = card_dir(root, pack, slot)
    if not (directory / "accept.json").is_file():
        return seals, evidence
    try:
        record, meta = C.read_json(directory / "accept.json"), C.read_json(directory / "ctx.json")
        card_doc = C.read_json(directory / "card.json")
        if not complete:
            raise C.Refused("card_blind_incomplete", "a seal of this viewer is missing or no longer verifies", next_command("score", "--pack", pack))
        # The card is re-bound here: its context again, its bytes, the complete sealed account, and the records of its flight.
        regenerate_card(pack, root, slot, meta)
        if C.sha_bytes(C.json_bytes(card_doc)) != record["card_sha256"]:
            raise C.Refused("card_record_mismatch", "the accepted card differs from the hash recorded when it was accepted", next_command("score", "--pack", pack))
        if record["blind_sha256"] != blind_digest(valid) or meta["blind_sha256"] != record["blind_sha256"]:
            raise C.Refused("card_binding_stale", "the sealed account changed after the card was accepted", next_command("score", "--pack", pack))
        if (record["movie_sha256"], record["manifest_sha256"]) != (manifest["movie"]["sha256"], manifest_sha):
            raise C.Refused("card_binding_mismatch", "the accepted card names another movie or manifest", next_command("score", "--pack", pack))
        attestation = X.recheck(record, meta, directory, protocol, ledger, observe_command(pack, slot, "card"))
    except (C.Refused, C.Harness) as exc:
        problems.append(f"card_invalid:{getattr(exc, 'reason', 'harness_error')}")
    else:
        verdict = {**evaluate(card_doc), "seat": record["seat"], "model": record["model"],
                    "card_sha256": record["card_sha256"], "blind_sha256": record["blind_sha256"],
                    "defects": card_doc["defects"], "summary": card_doc["summary"],
                    "frames_opened": sum(response["frames_opened"] for _, response in valid),
                    "frames_listed": sum(response["segment"]["count"] for _, response in valid),
                    "observer": attestation["kind"], "context_version": card_version(meta),
                    "attestation": X.summary(attestation)}
        verdict["incomplete_viewing"] = verdict["frames_opened"] < verdict["frames_listed"]
        evidence["card"] = verdict
    # The judgment is read again whatever became of the card: it is evidence of its own.
    evidence["match"] = judged_match(pack, root, slot, valid, complete, manifest, manifest_sha, protocol, ledger, problems)
    return seals, evidence


def judged_match(pack, root, slot, valid, complete, manifest, manifest_sha, protocol, ledger, problems):
    """Read the recorded judgment of a slot again: its context, its bytes, its records, and its quotations."""
    directory = match_dir(root, pack, slot)
    if not (directory / "accept.json").is_file():
        return None
    try:
        record, meta = C.read_json(directory / "accept.json"), C.read_json(directory / "ctx.json")
        judgment = C.read_json(directory / "judgment.json")
        brief = load_brief(pack, root)
        if not complete:
            raise C.Refused("match_blind_incomplete", "a seal of this viewer is missing or no longer verifies", observe_command(pack, slot, "match"))
        if not brief or not brief.get("contract"):
            raise C.Refused("action_contract_unbound", "no action contract is bound to this pack", observe_command(pack, slot, "match"))
        regenerate_match(pack, root, slot, meta)
        if C.sha_bytes(C.json_bytes(judgment)) != record["judgment_sha256"]:
            raise C.Refused("match_record_mismatch", "the accepted judgment differs from the hash recorded when it was accepted", observe_command(pack, slot, "match"))
        if record["blind_sha256"] != blind_digest(valid) or meta["blind_sha256"] != record["blind_sha256"]:
            raise C.Refused("match_binding_stale", "the sealed account changed after the judgment was accepted", observe_command(pack, slot, "match"))
        if (record["movie_sha256"], record["manifest_sha256"]) != (manifest["movie"]["sha256"], manifest_sha):
            raise C.Refused("match_binding_mismatch", "the accepted judgment names another movie or manifest", observe_command(pack, slot, "match"))
        attestation = X.recheck(record, meta, directory, protocol, ledger, observe_command(pack, slot, "match"))
        found = A.verify_judgment(judgment, valid, A.compile_contract(brief["contract"]))
    except (C.Refused, C.Harness) as exc:
        problems.append(f"match_invalid:{getattr(exc, 'reason', 'harness_error')}")
        return None
    return {**found, "judge": record["seat"], "judge_model": record["model"], "observer": attestation["kind"],
            "judgment_sha256": record["judgment_sha256"], "blind_sha256": record["blind_sha256"],
            "attestation": X.summary(attestation)}


def score(pack, root=None, ledger=None):
    """Panel verdict of a pack. Nothing is taken from a stored verdict: every seal and card is verified again.

    Both preregistered primaries must have a card that passes on its own, from a swarm observer whose
    records still close, over a complete sealed account that names the action, with technical PASS.
    """
    pack, root = Path(pack), as_root(root)
    protocol = C.load_protocol()
    manifest, manifest_sha = R.load_manifest(pack)
    verified = R.verify(pack, pixels=False)
    viewers = load_viewers(root, pack)
    if (viewers["movie_sha256"], viewers["manifest_sha256"]) != (manifest["movie"]["sha256"], manifest_sha):
        raise C.Refused("pack_reregistered", "the pack changed after registration; register a new pack",
                        next_command("register", "--pack", pack))
    primary = primaries(protocol)
    brief = load_brief(pack, root)
    technical_path = panel_root(root, pack) / "technical.json"
    technical_verdict = C.read_json(technical_path)["verdict"] if technical_path.is_file() else None
    reasons = []
    if verified["sampling_rule"] != protocol["sampling"]["rule"]:
        reasons.append("contact_window_landing_only")
    # A primary on another seat of the swarm registry is not the panel that was preregistered.
    registry_seats = {path.stem for path in X.SEATS.glob("*.json")} if X.SEATS is not None and X.SEATS.is_dir() else set()
    for slot in primary:
        seat = viewers["slots"].get(slot, {}).get("seat")
        if seat in registry_seats and seat != protocol["seats"][slot]["seat"]:
            reasons.append(f"slot_not_preregistered:{slot}")
    if len({viewers["slots"].get(slot, {}).get("seat") for slot in primary}) != len(primary):
        reasons.append("panel_not_independent")
    if technical_verdict != "PASS":
        reasons.append("technical_ausente" if technical_verdict is None else "technical_hold")
    evidence, cards, blind = {}, {}, {}
    for slot in sorted(viewers["slots"]):
        seals, found = slot_evidence(pack, root, slot, manifest, manifest_sha, protocol, ledger)
        evidence[slot] = {key: value for key, value in found.items() if key != "card"}
        evidence[slot]["card"] = None
        reasons.extend(found["problems"])
        blind[slot] = seals
        if found["card"] is not None:
            cards[slot] = found["card"]
            evidence[slot]["card"] = {"card_sha256": found["card"]["card_sha256"], "observer": found["card"]["observer"],
                                      "pass": found["card"]["pass"]}
            if found["card"]["observer"] != "swarm":
                reasons.append(f"scripted_observer:{slot}")
            if found["card"]["incomplete_viewing"]:
                reasons.append(f"incomplete_viewing:{slot}")
    scored = [cards[slot] for slot in primary if slot in cards]
    for slot in primary:
        if slot not in cards:
            reasons.append(f"missing_card:{slot}")
    seen = {}
    for slot in sorted(cards):
        fingerprint = C.sha_bytes(C.json_bytes({"scores": cards[slot]["scores"], "defects": cards[slot]["defects"],
                                                "summary": cards[slot]["summary"]}))
        if fingerprint in seen:
            reasons.append(f"copied_card:{slot}={seen[fingerprint]}")
        seen.setdefault(fingerprint, slot)
    agreement = {"axis_spread": {}, "max_spread": None, "split_on_release": None, "reserve_required": False}
    if len(scored) == len(primary) and len(scored) >= 2:
        spread = {axis: max(card["scores"][axis] for card in scored) - min(card["scores"][axis] for card in scored)
                  for axis in C.AXES}
        agreement = {"axis_spread": spread, "max_spread": max(spread.values()),
                     "split_on_release": len({card["pass"] for card in scored}) > 1,
                     "reserve_required": max(spread.values()) >= protocol["panel"]["axis_spread_trigger"]
                     or len({card["pass"] for card in scored}) > 1}
        if agreement["reserve_required"]:
            reasons.append("reserve_required")
    # Whether the sealed account names the action is decided by a verified judgment, never by the viewer.
    action = {}
    for slot in sorted(viewers["slots"]):
        found, card = evidence[slot].get("match"), cards.get(slot)
        evidence[slot]["match"] = None if found is None else {"match": found["match"], "observer": found["observer"],
                                                              "judge": found["judge"], "judgment_sha256": found["judgment_sha256"]}
        action[slot] = found or {"match": None, "reason": "no valid judgment is on record for the sealed account of this slot"}
        if found is not None and not found["match"]:
            reasons.append(f"blind_action_unconfirmed:{slot}")
        if slot in primary and card is not None:
            if card["observer"] == "swarm":
                if found is None:
                    reasons.append(f"blind_action_unjudged:{slot}")
                elif found["observer"] != "swarm":
                    reasons.append(f"scripted_judge:{slot}")
                    reasons.append(f"blind_action_unjudged:{slot}")
    if any(not card["pass"] for card in scored) or len(scored) < len(primary):
        reasons.insert(0, "card_not_passing")
    reasons = list(dict.fromkeys(reasons))
    quorum = {"required": primary, "present": [slot for slot in primary if slot in cards], "met": len(scored) == len(primary)}
    result = {"status": "SCORED", "verdict": "PASS" if not reasons else "HOLD", "reasons": reasons,
              "technical_verdict": technical_verdict, "protocol": C.VERSION, "rubric_version": protocol["rubric_version"],
              "sampling_rule": verified["sampling_rule"], "contact_window": verified["contact_window"],
              "pack": str(pack), "movie_sha256": manifest["movie"]["sha256"], "manifest_sha256": manifest_sha,
              "thresholds": protocol["thresholds"], "quorum": quorum, "cards": cards, "agreement": agreement,
              "action_match": action, "evidence": evidence,
              "blind_accounts": {slot: [{"segment": number, "frames": [response["segment"]["first_index"], response["segment"]["last_index"]],
                                        "account": response["account"], "events": response["events"],
                                        "unclear": response["unclear"], "evidence": response["evidence"],
                                        "response_sha256": record["response_sha256"], "cannot_see": record["cannot_see"]}
                                       for number, (record, response) in enumerate(blind[slot])]
                                 for slot in sorted(viewers["slots"])}}
    if reasons:
        result.update(reason="panel_incomplete", retry_when="when the recorded review requirements are met",
                      next_command=next_command("score", "--root", root, "--pack", pack))
    return result, (0 if not reasons else 1)


