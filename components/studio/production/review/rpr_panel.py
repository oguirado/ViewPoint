def blind_digest(seals):
    return C.sha_text("".join(f"{record['segment']}:{record['response_sha256']}\n" for record, _ in seals))


def clip(text, limit):
    return text if len(text) <= limit else text[:limit - 1] + "…"


def camera_text(declared, technical):
    camera = (declared or {}).get("camera")
    if not camera:
        return "AUSENTE (the declared plan of this movie names no camera)"
    declared_text = (f"\"{camera['name']}\", {camera['lens_mm']:g} mm lens on a {camera['sensor_width_mm']:g} mm sensor, "
                     f"location {camera['location_m']} m, rotation {camera['rotation_euler_rad']} rad, declared in the "
                     f"set registration with SHA-256 `{camera['source_sha256']}`")
    confirmation = (technical or {}).get("camera") or {"status": "AUSENTE", "how": "no technical receipt is bound"}
    return f"{declared_text}. Receipt of this movie: {confirmation['status']} ({confirmation['how']})."


def card_inputs(pack, root, slot, nonce):
    protocol = C.load_protocol()
    manifest, manifest_sha = R.load_manifest(pack)
    info = load_viewers(root, pack)["slots"][slot]
