def plan_segments(manifest, protocol):
    """Chronological chunks of at most segment_max_frames listed frames."""
    limit = protocol["blind"]["segment_max_frames"]
    segments, current = [], []
    for sample in manifest["samples"]:
        current.append(sample["index"])
        if len(current) == limit:
            segments.append(current)
            current = []
    if current:
        segments.append(current)
    return [{"segment": number, "first_index": indices[0], "last_index": indices[-1], "count": len(indices)}
            for number, indices in enumerate(segments)]


def load_viewers(root, pack):
    path = panel_root(root, pack) / "viewers.json"
    if not path.is_file():
        raise C.Refused("pack_unregistered", "register the viewer slots of the pack first",
                        next_command("register", "--pack", pack))
    record = C.read_json(path)
    if record.get("protocol_sha256") != C.sha_file(C.PROTOCOL_FILE):
        raise C.Refused("registered_protocol_changed", "restore the protocol bytes pinned at registration",
                        next_command("register", "--root", root, "--pack", pack))
    return record


