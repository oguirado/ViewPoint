    directory = blind_dir(root, pack, slot, meta["segment"])
    ctx, task, rebuilt = build_blind(pack, root, slot, meta["segment"], meta["brief_nonce"], meta.get("context_version", 1))
    on_disk = (directory / "ctx.md").read_text(encoding="utf-8") if (directory / "ctx.md").is_file() else ""
    if rebuilt != meta or C.sha_text(on_disk) != meta["ctx_sha256"] or C.sha_text(task) != meta["task_sha256"]:
        hits, shared = leak_scan(on_disk, protocol_with_terms(), (load_brief(pack, root) or {}).get("text"))
        if hits or shared:
            raise C.Refused("disclosed_brief",
                            "a first viewer must not be told the intended action; issue a clean context and a new viewer slot",
                            next_command("blind-ctx", "--pack", pack, "--slot", slot, "--segment", meta["segment"]))
        raise C.Refused("modified_brief", "the first viewing was shown a context that differs from the sealed one",
                        next_command("blind-ctx", "--pack", pack, "--slot", slot, "--segment", meta["segment"]))
    return ctx


