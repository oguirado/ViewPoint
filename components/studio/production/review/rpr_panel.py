FORMAT_FAILURES = ("evidence_mismatch", "evidence_duplicate", "evidence_missing", "response_shape",
                   "response_binding_mismatch", "response_not_json", *A.QUOTE_FAILURES)


def worker_depth():
    """Nesting depth of this process, read the way the swarm CLI reads it."""
    depths = []
    for name in ("NEWTON_DEPTH", "NEWTON_PROFUNDIDAD", "SWARM_DEPTH"):
        try:
            depths.append(int(os.environ.get(name, "0") or 0))
        except ValueError:
            depths.append(1)
    return max(depths)


def oneshot_argv(seat, ctx, task, wave, kind, protocol, adapter=None):
    """One call to the installed swarm CLI, or to a scripted adapter in tests."""
    if not adapter and not OBSERVER:
        raise C.Harness("supply the executable observer adapter with --observer")
    head = [str(adapter or OBSERVER)]
    return [*head, "oneshot", "--seat", seat, "--effort", protocol["effort"], "--tools",
            "--sources", str(ctx), "--task", str(task), "--allow-unqualified", "--wall-s", str(protocol["wall_s"][kind]),
            "--result-chars", str(protocol["result_chars"]), "--wave-dir", str(wave)]


def job_context(job, root):
    """Return (context metadata, directory) of a job, creating the sealed context once."""
    pack, slot = Path(job["pack"]), job["slot"]
    if job["kind"] == "blind":
        return (ensure_blind_context(pack, root, slot, job["segment"]),
                blind_dir(root, pack, slot, job["segment"]))
    if job["kind"] == "match":
        return ensure_match_context(pack, root, slot), match_dir(root, pack, slot)
    return ensure_card_context(pack, root, slot), card_dir(root, pack, slot)


def job_done(job, root):
    pack, slot = Path(job["pack"]), job["slot"]
    if job["kind"] == "blind":
        return (blind_dir(root, pack, slot, job["segment"]) / "seal.json").is_file()
    if job["kind"] == "match":
        return (match_dir(root, pack, slot) / "accept.json").is_file()
    return (card_dir(root, pack, slot) / "accept.json").is_file()


def spawn(job, root, adapter=None):
    """Start one observer call without waiting. Returns (Popen, output path)."""
    if worker_depth() > 0:
        raise C.Refused("nested_observer_launch_refused",
                        "start the job list from a depth-0 shell; a swarm worker may not launch observers",
                        next_command("observe"))
    meta, directory = job_context(job, root)
    attempt = job.get("attempt", 0)
    argv = oneshot_argv(meta["seat"], directory / "ctx.md", directory / "task.md",
                        directory / f"wave-a{attempt}", job["kind"], C.load_protocol(), adapter)
    out, err = directory / f"oneshot.a{attempt}.json", directory / f"oneshot.a{attempt}.err"
    if out.exists():
        raise C.Harness(f"attempt {attempt} of {meta['slot']} {job['kind']} already has an output; nothing is overwritten")
    (directory / f"command.a{attempt}.json").write_text(json.dumps(
        {"argv": argv, "cwd": str(root), "adapter": "scripted" if adapter else "swarm", "depth": worker_depth(),
         "context_bytes": meta["context_bytes"], "task_bytes": meta["task_bytes"], "ratio": meta["ratio"],
         "ctx_sha256": meta["ctx_sha256"], "task_sha256": meta["task_sha256"]}, indent=1) + "\n")
    child = subprocess.Popen(argv, cwd=str(root), env=child_env(), stdin=subprocess.DEVNULL,
                             stdout=out.open("wb"), stderr=err.open("wb"))
    return child, out


def child_env():
    """Pinned locale and clock, no display; everything else is inherited as it is now."""
    env = {key: value for key, value in os.environ.items()
           if key not in ("DISPLAY", "WAYLAND_DISPLAY", "XAUTHORITY")}
    env.update({"LC_ALL": "C.UTF-8", "LANG": "C.UTF-8", "TZ": "UTC"})
    return env


def finish(job, root):
    """Seal or accept the response filed for a job."""
    pack, slot = Path(job["pack"]), job["slot"]
    attempt = job.get("attempt", 0)
    if job["kind"] == "blind":
        return seal(pack, root, slot, job["segment"],
                    blind_dir(root, pack, slot, job["segment"]) / f"oneshot.a{attempt}.json")
    if job["kind"] == "match":
        return judge(pack, root, slot, match_dir(root, pack, slot) / f"oneshot.a{attempt}.json")
    return accept(pack, root, slot, card_dir(root, pack, slot) / f"oneshot.a{attempt}.json")


def observe(job, root, adapter=None):
    """Run one observer call to completion, then seal or accept its response."""
    child, _ = spawn(job, root, adapter)
    return {"observer_rc": child.wait(), **finish(job, root)}


def drive(jobs_path, log_path, limits, attempts, poll_s=2.0, root=None, adapter=None, format_retries=4,
          retry_delay=60):
    """Run a job list with a per-seat concurrency limit. Every response is sealed where it lands.

    An attempt is never overwritten. A call that returned nothing is retried on a new attempt
    number, and so is a response that fails on form (bad token, wrong shape); a response that is
    valid is sealed as it is, favourable or not. A response whose observer records do not close
    is refused and counts as a failure: it is never sealed.
    """
    root = as_root(root)
    limits = limits or {seat["seat"]: 1 for seat in C.load_protocol()["seats"].values()}
    jobs = [json.loads(line) for line in Path(jobs_path).read_text().splitlines() if line.strip()]
    pending, running, failures = list(jobs), [], 0
    with Path(log_path).open("a", encoding="utf-8") as log:
        def note(**fields):
            log.write(json.dumps(fields, sort_keys=True, ensure_ascii=False) + "\n")
            log.flush()

        while pending or running:
            for job in list(pending):
                if job.get("not_before", 0) > time.monotonic():
                    continue
                try:
                    meta, _ = job_context(job, root)
                except (C.Refused, C.Harness) as exc:
                    pending.remove(job)
                    failures += 1
                    note(event="refused", reason=getattr(exc, "reason", str(exc)), **job)
                    continue
                seat = meta["seat"]
                if sum(1 for _, held, _ in running if held == seat) >= limits.get(seat, 1):
                    continue
                if job_done(job, root):
                    pending.remove(job)
                    note(event="already_done", **job)
                    continue
                pending.remove(job)
                try:
                    child, _ = spawn(job, root, adapter)
                except C.Refused as exc:
                    failures += 1
                    note(event="refused", reason=exc.reason, retry_when=exc.retry_when, **job)
                    continue
                except C.Harness as exc:
                    failures += 1
                    note(event="harness_error", error=str(exc), **job)
                    continue
                running.append((child, seat, (job, time.monotonic())))
                note(event="launched", pid=child.pid, seat=seat, **job)
            for entry in list(running):
                child, seat, (job, started) = entry
                if child.poll() is None:
                    continue
                running.remove(entry)
                outcome = {"event": "finished", "observer_rc": child.returncode, "seat": seat,
                           "wall_s": round(time.monotonic() - started, 1), **job}
                try:
                    result = finish(job, root)
                    outcome.update(status=result["status"], model=result.get("model"),
                                   sha=result.get("response_sha256") or result.get("card_sha256"))
                except C.Refused as exc:
                    outcome.update(status="REFUSED", reason=exc.reason)
                    used, attempt = job.get("format_retries", 0), job.get("attempt", 0)
                    retry = None
                    if exc.reason == "observer_failed" and attempt + 1 < attempts:
                        retry = "observer_retry"
                    elif exc.reason in FORMAT_FAILURES and used < format_retries:
                        retry = "format_retry"
                    if retry:
                        nxt = attempt + 1
                        pending.append({**job, "attempt": nxt,
                                        "format_retries": used + (retry == "format_retry"),
                                        "not_before": time.monotonic() + (retry_delay * nxt if retry == "observer_retry" else 0)})
                        outcome.update(requeued=True, retry_kind=retry)
                    else:
                        failures += 1
                except C.Harness as exc:
                    outcome.update(status="HARNESS_ERROR", error=str(exc))
                    failures += 1
                note(**outcome)
            if pending or running:
                time.sleep(poll_s)
    return failures


# ------------------------------------------------------------------ job lists
def pack_rule(pack):
    return R.sampling_rule(R.load_manifest(pack)[0]["sampling"])


def registered_packs(root, rule=None):
    """Every registered panel, or only those built under the rule in force."""
    directory = Path(root) / "panel"
    found = [(path, C.read_json(path / "viewers.json")) for path in sorted(directory.iterdir())
             if (path / "viewers.json").is_file()] if directory.is_dir() else []
    return [(path, viewers) for path, viewers in found if rule is None or pack_rule(Path(viewers["pack"])) == rule]


def sealed_through(pack, root, slot):
    """True when every segment of a slot carries a seal file."""
    manifest, _ = R.load_manifest(pack)
    return all((blind_dir(root, pack, slot, segment) / "seal.json").is_file()
               for segment in range(len(plan_segments(manifest, C.load_protocol()))))


def job_lists(root, slots=None, labels=None):
    """Observer jobs that are still open under the rule in force: blind, card, and the judgment of each account.

    Packs built under a retired rule are never driven again; what they hold is re-scored where
    it is still valid. A judgment is listed for every viewer whose segments are all sealed and
    whose account has no accepted judgment.
    """
    protocol = C.load_protocol()
    blind, card, match = [], [], []
    for _, viewers in registered_packs(root, protocol["sampling"]["rule"]):
        pack = Path(viewers["pack"])
        label = (labels or {}).get(pack.name, pack.name)
        segments = len(plan_segments(R.load_manifest(pack)[0], protocol))
        for slot in sorted(viewers["slots"]):
            if slots and slot not in slots:
                continue
            job = {"pack": str(pack), "slot": slot, "label": f"{label}/{slot}"}
            for segment in range(segments):
                if not (blind_dir(root, pack, slot, segment) / "seal.json").is_file():
                    blind.append({"kind": "blind", "segment": segment, **job})
            if not (card_dir(root, pack, slot) / "accept.json").is_file():
                card.append({"kind": "card", **job})
            if sealed_through(pack, root, slot) and not (match_dir(root, pack, slot) / "accept.json").is_file():
                match.append({"kind": "match", **job})
    blind.sort(key=lambda job: (job["segment"], job["slot"], job["label"]))
    card.sort(key=lambda job: (job["slot"], job["label"]))
    match.sort(key=lambda job: (job["slot"], job["label"]))
    return blind, card, match


def reserve_jobs(root):
    """Register and list the reserve viewer for every pack whose primaries split."""
    protocol = C.load_protocol()
    blind, card, match = [], [], []
    for _, viewers in registered_packs(root, protocol["sampling"]["rule"]):
        pack = Path(viewers["pack"])
        if not score(pack, root)[0]["agreement"].get("reserve_required"):
            continue
        if any(slot not in viewers["slots"] for slot in reserves(protocol)):
            register_reserve(pack, root)
        extra_blind, extra_card, extra_match = job_lists(root, reserves(protocol))
        blind += extra_blind
        card += extra_card
        match += extra_match
    return blind, card, match


def write_jobs(path, jobs):
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text("".join(json.dumps(job, sort_keys=True) + "\n" for job in jobs))


