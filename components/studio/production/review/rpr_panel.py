def lineage(seat):
    """Where a seat comes from, read from the swarm registry; a seat outside it is a test seat."""
    try:
        data, path, digest = X.registry_seat(seat)
    except C.Harness:
        return {"family": "scripted", "registry": None, "note": "not a seat of the swarm registry; a test observer"}
    return {"family": data.get("family"), "model": data.get("model"), "adapter": Path(str(data.get("launcher", ""))).name,
            "account": (data.get("quota") or {}).get("account"),
            "qualification_state": (data.get("qualification") or {}).get("state"), "seat_state": data.get("state"),
            "registry": path, "registry_sha256": digest}


def register(pack, root=None, seats=None):
    """Create the viewer slots of a pack. The panel is the one the protocol preregistered.

    The command line has no option to choose seats: `seats` exists for a scripted test panel.
    Two primaries on one seat are refused, and so is a pack built under a retired rule.
    """
    protocol = C.load_protocol()
    manifest, manifest_sha = R.load_manifest(pack)
    verified = R.verify(pack)
    if verified["sampling_rule"] != protocol["sampling"]["rule"]:
        raise C.Refused("pack_rule_superseded",
                        "this pack was built under a retired sampling rule; build the pack again under the rule in force",
                        next_command("build"))
    required = {*primaries(protocol), *reserves(protocol), "judge"}
    if not required <= protocol["seats"].keys() or X.SEATS is None:
        raise C.Refused("observer_configuration_required", "supply a protocol with seats and --seat-registry",
                        next_command("register", "--pack", pack))
    for slot in sorted(required):
        X.check_registry(slot, protocol)
    chosen = {slot: protocol["seats"][slot]["seat"] for slot in primaries(protocol)}
    chosen.update({slot: seat for slot, seat in (seats or {}).items() if slot in chosen})
    if len(set(chosen.values())) != len(chosen):
        raise C.Refused("panel_not_independent", "the primary viewers of one pack sit on different seats",
                        next_command("register", "--pack", pack))
    path = panel_root(root, pack) / "viewers.json"
    data = {"protocol": C.VERSION, "protocol_sha256": C.sha_file(C.PROTOCOL_FILE),
            "pack": str(Path(pack).resolve()), "movie_sha256": manifest["movie"]["sha256"],
            "manifest_sha256": manifest_sha, "slots": {}}
    if path.is_file():
        data = load_viewers(root, pack)
        if (data["movie_sha256"], data["manifest_sha256"]) != (manifest["movie"]["sha256"], manifest_sha):
            raise C.Refused("pack_reregistered", "the pack changed after registration; register a new pack",
                            next_command("register", "--pack", pack))
    for slot, seat in chosen.items():
        current = data["slots"].get(slot)
        if current and current["seat"] != seat:
            raise C.Refused("slot_seat_changed", "a viewer slot keeps the seat it was registered with",
                            next_command("register", "--pack", pack))
        if not current:
            data["slots"][slot] = {"seat": seat, "viewer_token": secrets.token_hex(8),
                                   "card_token": secrets.token_hex(8), "lineage": lineage(seat)}
    data.update(sampling_rule=verified["sampling_rule"],
                panel={"primaries": primaries(protocol), "reserve": reserves(protocol),
                       "provenance": protocol["panel"]["provenance"]})
    C.write_json(path, data)
    return {"status": "REGISTERED", "pack": str(pack), "movie_sha256": manifest["movie"]["sha256"],
            "slots": {slot: info["seat"] for slot, info in sorted(data["slots"].items())},
            "independent": len({info["seat"] for info in data["slots"].values()}) == len(data["slots"])}


def register_reserve(pack, root=None):
    protocol = C.load_protocol()
    manifest, manifest_sha = R.load_manifest(pack)
    viewers = load_viewers(root, pack)
    if (viewers["movie_sha256"], viewers["manifest_sha256"]) != (manifest["movie"]["sha256"], manifest_sha):
        raise C.Refused("pack_reregistered", "the pack changed after registration; register a new pack",
                        next_command("register", "--pack", pack))
    for slot in reserves(protocol):
        seat = protocol["seats"][slot]["seat"]
        current = viewers["slots"].get(slot)
        if current and current["seat"] != seat:
            raise C.Refused("slot_seat_changed", "a viewer slot keeps the seat it was registered with",
                            next_command("register", "--pack", pack))
        if not current:
            viewers["slots"][slot] = {"seat": seat, "viewer_token": secrets.token_hex(8),
                                      "card_token": secrets.token_hex(8), "lineage": lineage(seat)}
    C.write_json(panel_root(root, pack) / "viewers.json", viewers)
    return {"status": "RESERVE_REGISTERED", "pack": str(pack), "slots": reserves(protocol)}


def set_binding(pack, root, name, record):
    """Store the brief or the technical verdict once. Neither can be rewritten afterwards."""
    path = panel_root(root, pack) / f"{name}.json"
    if path.is_file():
        if C.read_json(path) != record:
            raise C.Refused(f"{name}_already_set", "a sealed binding cannot be replaced; register a new pack",
                            next_command(name, "--pack", pack))
        return {"status": name.upper(), "sha256": C.sha_file(path), "unchanged": True}
    C.write_json(path, record, readonly=True)
    return {"status": name.upper(), "sha256": C.sha_file(path)}


def brief_record(pack, root, text_file, source, contract_path=None):
    text = Path(text_file).read_text(encoding="utf-8").strip()
    if not text:
        raise C.Harness("brief text is empty")
    manifest, _ = R.load_manifest(pack)
    record = {"movie_sha256": manifest["movie"]["sha256"], "text": text, "source": source,
              "text_sha256": C.sha_text(text)}
    if contract_path:
        contract = A.load_contract(contract_path)
        try:
            A.compile_contract(contract)  # a contract that does not compile is never bound
        except A.BadContract as exc:
            raise C.Harness(f"the action contract does not compile: {exc}") from exc
        record.update(contract=contract, contract_sha256=C.sha_file(contract_path),
                      contract_path=str(Path(contract_path).resolve()))
    return record


def camera_confirmation(declared, document):
    """Whether the technical receipt confirms, for this movie, the camera the plan declares."""
    camera = (declared or {}).get("camera")
    if not camera:
        return {"status": "AUSENTE", "how": "the declared plan of this movie names no camera"}
    pinned = str(((document.get("inputs") or {}).get("set_registration") or {}).get("sha256") or "")
    if pinned == camera["source_sha256"]:
        return {"status": "confirmed", "how": "the receipt of this movie pins the same set registration digest "
                "the declared camera cites; the receipt records no camera transform of its own",
                "set_registration_sha256": pinned}
    return {"status": "unconfirmed", "how": "the receipt of this movie pins another set registration digest"
            if pinned else "the receipt of this movie records no set registration digest",
            "set_registration_sha256": pinned or None}


def technical_record(pack, root, receipt):
    document = C.read_json(receipt)
    manifest, _ = R.load_manifest(pack)
    sha = document.get("outputs", {}).get("movie", {}).get("sha256") or document.get("video_sha256")
    verdict = document.get("status") or document.get("verdict")
    if sha != manifest["movie"]["sha256"]:
        raise C.Refused("technical_receipt_mismatch", "supply a technical receipt bound to the pinned movie",
                        next_command("technical", "--pack", pack))
    return {"movie_sha256": sha, "verdict": verdict, "receipt_sha256": C.sha_file(receipt),
            "receipt": str(Path(receipt).resolve()),
            "camera": camera_confirmation(manifest["declared"], document)}


