def timeline_map(manifest, segments):
    """Compact statement of which frames of the whole movie are listed, and how the segments cut them."""
    parts = []
    for sample in manifest["samples"]:
        if parts and sample["step"] == 1 and parts[-1][1] == sample["index"] - 1:
            parts[-1][1] = sample["index"]
        else:
            parts.append([sample["index"], sample["index"], sample["step"]])
    pieces, group = [], []

    def flush():
        if len(group) == 1:
            low, _, step = group[0]
            pieces.append(f"{low} (first frame)" if low == manifest["samples"][0]["index"] else f"{low} (step {step})")
        elif group:
            pieces.append(", ".join(str(low) for low, _, _ in group) + f" (step {group[0][2]})")

    for low, high, step in parts:
        if low == high:
            if group and group[-1][2] != step:
                flush()
                group.clear()
            group.append([low, high, step])
        else:
            flush()
            group.clear()
            pieces.append(f"{low}–{high} successive")
    flush()
    cuts = ", ".join(f"{s['segment'] + 1}: {s['first_index']}–{s['last_index']}" for s in segments)
    return (f"- Listed frames of the whole movie, in order: {'; '.join(pieces)}.\n"
            f"- Segments, as number: frame indices: {cuts}.")


