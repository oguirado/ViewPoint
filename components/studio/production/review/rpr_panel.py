def to_int(value):
    if isinstance(value, bool):
        raise ValueError("boolean where an integer is required")
    if isinstance(value, int):
        return value
    if isinstance(value, float) and value.is_integer():
        return int(value)
    if isinstance(value, str) and re.fullmatch(r"\s*-?\d+\s*", value):
        return int(value)
    raise ValueError(f"not an integer: {value!r}")


def extract_json(result):
    """Return (object, extra_text) for the first JSON object in a result string."""
    if isinstance(result, dict):
        return result, False
    if not isinstance(result, str):
        return None, False
    text = re.sub(r"^```[a-zA-Z]*\s*|\s*```$", "", result.strip()).strip()
    start = text.find("{")
    if start < 0:
        return None, False
    try:
        obj, end = DECODER.raw_decode(text, start)
    except ValueError:
        return None, False
    return obj, bool(text[:start].strip() or text[end:].strip())


def token_map(manifest):
    return {sample["index"]: sample["frame_token"] for sample in manifest["samples"]}


def parse_evidence(items, allowed, tokens, label, refuse):
    if not isinstance(items, list):
        raise ValueError("evidence must be a list")
    parsed, seen = [], set()
    for item in items:
        if not isinstance(item, dict) or not isinstance(item.get("observation"), str) or not item["observation"].strip():
            raise ValueError("each evidence item needs an observation")
        index = to_int(item.get("index"))
        token = str(item.get("frame_token", "")).strip().lower()
        if index not in allowed or tokens.get(index) != token:
            raise C.Refused("evidence_mismatch", f"{label}: frame {index} is not a listed frame with that token", refuse)
        if index in seen:
            raise C.Refused("evidence_duplicate", f"{label}: frame {index} is cited twice", refuse)
        seen.add(index)
        parsed.append({"index": index, "frame_token": token, "observation": item["observation"].strip()})
    return parsed


def parse_blind(response, manifest, meta, chosen):
    refuse = next_command("seal", "--pack", meta["pack"], "--slot", meta["slot"], "--segment", meta["segment"])
    if not isinstance(response, dict) or set(response) != BLIND_KEYS:
        raise C.Refused("response_shape", f"a first viewing response has exactly the keys {sorted(BLIND_KEYS)}", refuse)
    try:
        segment = response["segment"]
        binding = (response["viewer_token"], response["brief_nonce"], response["movie_sha256"],
                   response["manifest_sha256"], response["catalog_sha256"], to_int(segment.get("first_index")),
                   to_int(segment.get("last_index")), to_int(segment.get("count")))
        pixel_access, opened = response["pixel_access"], to_int(response["frames_opened"])
        account, events, unclear = response["account"], response["events"], response["unclear"]
    except (ValueError, AttributeError, TypeError) as exc:
        raise C.Refused("response_shape", f"a first viewing response is malformed: {exc}", refuse) from exc
    expected = (meta["viewer_token"], meta["brief_nonce"], meta["movie_sha256"], meta["manifest_sha256"],
                manifest["catalog_sha256"], chosen["first_index"], chosen["last_index"], chosen["count"])
    if binding != expected:
        raise C.Refused("response_binding_mismatch",
                        "the response does not echo the viewer token, nonce, digests and segment of its sealed context", refuse)
    if (not isinstance(pixel_access, bool) or opened < 0 or not isinstance(account, str) or not account.strip()
            or not isinstance(events, list) or not isinstance(unclear, list)
            or not all(isinstance(line, str) for line in unclear)):
        raise C.Refused("response_shape", "a first viewing response is malformed", refuse)
    allowed = set(range(chosen["first_index"], chosen["last_index"] + 1))
    tokens = token_map(manifest)
    parsed_events = []
    for event in events:
        if not isinstance(event, dict) or not isinstance(event.get("description"), str) or not event["description"].strip():
            raise C.Refused("response_shape", "each event needs a description", refuse)
        try:
            first, last = to_int(event.get("first_index")), to_int(event.get("last_index"))
        except ValueError as exc:
            raise C.Refused("response_shape", f"each event needs integer frame bounds: {exc}", refuse) from exc
        confidence = str(event.get("confidence", "")).strip().lower()
        if confidence not in CONFIDENCE or first > last or first not in allowed or last not in allowed:
            raise C.Refused("evidence_mismatch", f"event frames {first}–{last} ({confidence}) are outside the viewed segment", refuse)
        parsed_events.append({"description": event["description"].strip(), "first_index": first,
                              "last_index": last, "confidence": confidence})
    try:
        evidence = parse_evidence(response["evidence"], allowed, tokens, "blind", refuse)
    except ValueError as exc:
        raise C.Refused("response_shape", f"a first viewing response is malformed: {exc}", refuse) from exc
    minimum = C.load_protocol()["blind"]["min_evidence"]
    if pixel_access and len(evidence) < minimum:
        raise C.Refused("evidence_missing", f"a first viewing cites at least {minimum} listed frames", refuse)
    return {"viewer_token": meta["viewer_token"], "brief_nonce": meta["brief_nonce"],
            "movie_sha256": meta["movie_sha256"], "manifest_sha256": meta["manifest_sha256"],
            "catalog_sha256": manifest["catalog_sha256"],
            "segment": {"first_index": chosen["first_index"], "last_index": chosen["last_index"], "count": chosen["count"]},
            "pixel_access": pixel_access, "frames_opened": opened, "account": account.strip(),
            "events": parsed_events, "evidence": evidence, "unclear": [line.strip() for line in unclear]}


def observer_record(oneshot, meta, manifest, manifest_sha, job_dir, oneshot_path, protocol, ledger=None, command=None):
    """Accept an observer output only when the swarm records close around it, and describe it."""
    command = command or observe_command(meta["pack"], meta["slot"], meta["kind"], meta.get("segment"))
    if not (oneshot.get("ok") is True and oneshot.get("outcome") == "done" and oneshot.get("rc") == 0):
        raise C.Refused("observer_failed", "the observer did not return a result; run it again from the same sealed context",
                        command)
    if oneshot.get("seat") != meta["seat"]:
        raise C.Refused("seat_mismatch", f"this slot is registered with seat {meta['seat']}",
                        command)
    found = re.search(r"\.a(\d+)\.json$", Path(oneshot_path).name)  # the driver files attempt N as oneshot.aN.json
    attempt = int(found.group(1)) if found else 0
    # The attestation is what makes the response observer evidence. Without it nothing is sealed.
    attestation = X.attest(meta, oneshot, job_dir, attempt, protocol, ledger, command)
    response, extra = extract_json(oneshot.get("result"))
    if not isinstance(response, dict):
        raise C.Refused("response_not_json", "the observer did not return a JSON object; run it again from the same sealed context",
                        command)
    receipt_path = oneshot.get("receipt_path")
    common = {"protocol": C.VERSION, "stage": meta["kind"], "slot": meta["slot"], "seat": meta["seat"],
              "model": oneshot.get("model"), "movie_sha256": manifest["movie"]["sha256"], "manifest_sha256": manifest_sha,
              "catalog_sha256": manifest["catalog_sha256"], "brief_nonce": meta["brief_nonce"],
              "ctx_sha256": meta["ctx_sha256"], "task_sha256": meta["task_sha256"],
              "context_bytes": meta["context_bytes"], "task_bytes": meta["task_bytes"],
              "context_task_ratio": meta["ratio"], "raw_result_sha256": C.sha_text(str(oneshot.get("result"))),
              "response_had_extra_text": extra, "receipt_path": receipt_path,
              "receipt_sha256": R.sha_or_none(receipt_path) if receipt_path else None,
              "usage": oneshot.get("usage"), "sealed_at_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
              "observer_kind": attestation["kind"], "attempt": attempt, "oneshot": str(oneshot_path),
              "oneshot_sha256": C.sha_file(oneshot_path), "attestation": attestation}
    return response, common


def append_seal(root, pack, record):
    with (panel_root(root, pack) / "seals.jsonl").open("a", encoding="utf-8") as stream:
        stream.write(json.dumps(record, sort_keys=True, ensure_ascii=False) + "\n")


def seal(pack, root, slot, segment, oneshot_path, ledger=None):
    """Accept a first viewing only if it answers the sealed, undisclosed context."""
    pack, root = Path(pack), as_root(root)
    protocol = C.load_protocol()
    meta = ensure_blind_context(pack, root, slot, segment)
    regenerate_blind(pack, root, slot, meta)
    R.verify(pack, pixels=False)
    manifest, manifest_sha = R.load_manifest(pack)
    chosen = plan_segments(manifest, protocol)[segment]
    directory = blind_dir(root, pack, slot, segment)
    if (card_dir(root, pack, slot) / "ctx.json").is_file() and not (directory / "seal.json").is_file():
        raise C.Refused("not_first_viewing", "the rubric was already released to this slot; a new viewing is not a first one",
                        next_command("score", "--pack", pack))
    response, common = observer_record(C.read_json(oneshot_path), meta, manifest, manifest_sha, directory,
                                       oneshot_path, protocol, ledger)
    parsed = parse_blind(response, manifest, meta, chosen)
    record = {**common, "segment": segment, "response_sha256": C.sha_bytes(C.json_bytes(parsed)),
              "cannot_see": not parsed["pixel_access"],
              "incomplete_viewing": parsed["pixel_access"] and parsed["frames_opened"] < chosen["count"]}
    if (directory / "seal.json").is_file():
        old = C.read_json(directory / "seal.json")
        if old["response_sha256"] != record["response_sha256"]:
            raise C.Refused("already_sealed", "a first viewing is sealed once; a different response needs a new viewer slot",
                            next_command("score", "--pack", pack))
        return {"status": "SEALED", **record, "unchanged": True}
    C.write_json(directory / "response.json", parsed, readonly=True)
    C.write_json(directory / "seal.json", record, readonly=True)
    append_seal(root, pack, record)
    return {"status": "SEALED", **record}


def load_seals(pack, root, slot):
    """Sealed first viewings of a viewer in order; (seals, index of the first unsealed segment or None)."""
    manifest, _ = R.load_manifest(pack)
    seals = []
    for number in range(len(plan_segments(manifest, C.load_protocol()))):
        directory = blind_dir(root, pack, slot, number)
        if not (directory / "seal.json").is_file():
            return seals, number
        seals.append((C.read_json(directory / "seal.json"), C.read_json(directory / "response.json")))
    return seals, None


