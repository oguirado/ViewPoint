def partial(viewer):
    """What one slot has on record, valid or not."""
    return {"seals": viewer["seals"], "segments": viewer["segments"], "complete": viewer["complete"],
            "observer": viewer["observer"], "attested": viewer["attested"], "card": viewer["card"],
            "problems": list(viewer["problems"])}


def card_view(card, action):
    return {"seat": card["seat"], "model": card["model"], "observer": card["observer"], "scores": card["scores"],
            "first_four_subtotal": card["first_four_subtotal"], "total": card["total"],
            "pass": card["pass"], "reasons": card["reasons"], "major_defects": card["major_defects"],
            "minor_defects": card["minor_defects"], "frames_opened": card["frames_opened"],
            "frames_listed": card["frames_listed"], "card_sha256": card["card_sha256"],
            "blind_sha256": card["blind_sha256"], "attestation": card["attestation"],
            "blind_action_match": action.get("match") if action else None,
            "blind_action_missing": action.get("missing", []) if action else None}


def canonical_axes(score_lists):
    """Per axis the median of the primary viewers: for two viewers, the lower score."""
    return {axis: sorted(scores[axis] for scores in score_lists)[(len(score_lists) - 1) // 2] for axis in C.AXES}


def calibrate(registry_path, out, root=None):
    """Canonical axis scores of each registered anchor, or AUSENTE with what is on record.

    An anchor is MEASURED only when both preregistered primaries hold a card from a swarm
    observer whose records still close, over a complete sealed account. Anything less is
    reported as partial observations and leaves the anchor AUSENTE.
    """
    root = as_root(root)
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    protocol = C.load_protocol()
    primary = primaries(protocol)
    rows = []
    for anchor in C.read_json(registry_path)["anchors"]:
        pack = root / "packs" / R.pack_id_for(anchor["movie_sha256"])
        row = {"run_id": anchor["run_id"], "pack": pack.name, "movie_sha256": anchor["movie_sha256"],
               "legacy_scores_cited": anchor["legacy_scores_cited"], "legacy_scores_source": anchor["legacy_scores_source"],
               "sampling_rule": protocol["sampling"]["rule"], "status": "AUSENTE", "reason": "pack_not_registered"}
        if (root / "panel" / pack.name / "viewers.json").is_file():
            verdict, _ = score(pack, root)
            row.update(manifest_sha256=verdict["manifest_sha256"], verdict=verdict["verdict"], reasons=verdict["reasons"],
                       quorum=verdict["quorum"], agreement=verdict["agreement"],
                       technical_verdict=verdict["technical_verdict"], action_match=verdict["action_match"],
                       evidence=verdict["evidence"], partial={slot: partial(viewer) for slot, viewer in verdict["evidence"].items()})
            votes = [slot for slot in primary if verdict["cards"].get(slot, {}).get("observer") == "swarm"]
            if verdict["quorum"]["met"] and len(votes) == len(primary):
                row["viewers"] = {slot: card_view(verdict["cards"][slot], verdict["action_match"].get(slot)) for slot in primary}
                row["canonical"] = {**canonical_axes([verdict["cards"][slot]["scores"] for slot in primary]),
                                    "viewer_count": len(primary), "method": "per-axis median of the primary viewers; the lower score of two"}
                row["spread"] = {axis: max(verdict["cards"][slot]["scores"][axis] for slot in primary)
                                 - min(verdict["cards"][slot]["scores"][axis] for slot in primary) for axis in C.AXES}
                row.update(status="MEASURED", reason=None)
            else:
                row["reason"] = "; ".join(f"{slot}: {verdict['evidence'][slot]['seals']} of {verdict['evidence'][slot]['segments']} "
                                          f"segments sealed, {'no' if slot not in verdict['cards'] else 'a'} valid card"
                                          for slot in primary) + f"; {len(votes)} of {len(primary)} primary cards from swarm observers"
        legacy = anchor.get("legacy_pack")
        if legacy and (root / "panel" / Path(legacy["pack"]).name / "viewers.json").is_file():
            old = root / legacy["pack"]
            held, _ = score(old, root)
            row["legacy_landing_only"] = {
                "pack": old.name, "manifest_sha256": held["manifest_sha256"], "sampling_rule": held["sampling_rule"],
                "contact_window": held["contact_window"], "verdict": held["verdict"], "reasons": held["reasons"],
                "evidence": held["evidence"], "action_match": held["action_match"],
                "cards": {slot: card_view(card, held["action_match"].get(slot)) for slot, card in held["cards"].items()},
                "status": "PARTIAL_OBSERVATIONS",
                "note": "Sealed before the round-2 rules under the superseded landing-only sampling. Re-scored under the "
                        "rules in force. Kept as partial evidence of these movies; never a canonical score."}
        rows.append(row)
    measured = sum(row["status"] == "MEASURED" for row in rows)
    result = {"protocol": C.VERSION, "rubric_version": protocol["rubric_version"], "thresholds": protocol["thresholds"],
              "sampling_rule": protocol["sampling"]["rule"],
              "status": "CALIBRATED" if rows and measured == len(rows) else "INCOMPLETE",
              "measured": measured, "anchors": rows, "out": str(out)}
    C.write_json(out / "CANONICAL.json", result)
    (out / "CANONICAL.md").write_text(render_canonical(rows), encoding="utf-8")
    states = {row["run_id"]: row["status"] for row in rows}
    if result["status"] == "CALIBRATED":
        return {"status": "CALIBRATED", "anchors": states, "measured": measured, "out": str(out)}, 0
    return {"status": "REFUSED", "reason": "calibration_incomplete",
            "retry_when": "every anchor holds a valid card from both preregistered primary seats",
            "next_command": next_command("score"),
            "anchors": states, "measured": measured, "out": str(out)}, 1


def render_canonical(rows):
    absent = "AUSENTE — no inventar"
    head = ("| Anchor | Status | Viewer (seat, model) | Textures and materials | Silhouette readability | Animation "
            "readability | Contact and staging | Technical artefacts | First four | Total | Card | Blind action match | "
            "Legacy textures / integrity / animation / staging / overall [CITED] |")
    rule = "|---|---|---|---:|---:|---:|---:|---:|---:|---:|---|---|---|"
    lines = ["# Canonical axis scores of the legacy anchors", "",
             "Canonical axes are those of `rp4.e2e-vision.v1`. An anchor is MEASURED only when both preregistered "
             "primary seats hold a card that still verifies over a complete sealed account. Legacy scores stay on "
             "their own scale, shown beside them for paired diagnostics; no arithmetic conversion is made.", "",
             "Rule in force: `" + (rows[0]["sampling_rule"] if rows else "") + "`, every frame of each declared "
             "foot-plant and hand-button interval inside a consecutive window.", "", head, rule]

    def legacy(row):
        return " / ".join(str(row["legacy_scores_cited"][key]) for key in ("textures", "integrity", "animation", "staging", "overall"))

    def cells(scores):
        return " | ".join(f"{scores[axis]} [MEASURED]" for axis in C.AXES)

    for row in rows:
        if row["status"] != "MEASURED":
            on_record = "; ".join(f"{slot}: {item['seals']}/{item['segments']} sealed, "
                                  f"{'card' if item['card'] else 'no card'} ({item['observer']})"
                                  for slot, item in row.get("partial", {}).items()) or row["reason"]
            lines.append(f"| {row['run_id']} | {absent} | {absent} | {absent} | {absent} | {absent} | {absent} | "
                         f"{absent} | {absent} | {absent} | {absent} | on record: {on_record} | {legacy(row)} |")
            continue
        for slot, viewer in sorted(row["viewers"].items()):
            match = viewer["blind_action_match"]
            lines.append(f"| {row['run_id']} | MEASURED | {slot} ({viewer['seat']}, {viewer['model']}) | {cells(viewer['scores'])} | "
                         f"{viewer['first_four_subtotal']} [MEASURED] | {viewer['total']} [MEASURED] | "
                         + ("PASS" if viewer["pass"] else "HOLD: " + ", ".join(viewer["reasons"]))
                         + f" | {absent if match is None else ('named' if match else 'not named: ' + ', '.join(viewer['blind_action_missing']))} | {legacy(row)} |")
        canonical = row["canonical"]
        lines.append(f"| {row['run_id']} | MEASURED | canonical (median of {canonical['viewer_count']}) | {cells(canonical)} | "
                     f"{sum(canonical[a] for a in C.AXES[:-1])} [MEASURED] | {sum(canonical[a] for a in C.AXES)} [MEASURED] | "
                     f"{row['verdict']}" + (f": {', '.join(row['reasons'])}" if row["reasons"] else "")
                     + f" | spread {' / '.join(str(row['spread'][axis]) for axis in C.AXES)} | {legacy(row)} |")
    kept = [row for row in rows if row.get("legacy_landing_only")]
    if kept:
        lines += ["", "## Observations kept from the superseded landing-only rule", "",
                  "Sealed before the round-2 rules. Re-scored under the rules in force and kept as partial evidence; "
                  "they are never a canonical score.", "", head, rule]
        for row in kept:
            held = row["legacy_landing_only"]
            if not held["cards"]:
                lines.append(f"| {row['run_id']} | PARTIAL | no valid card | {absent} | {absent} | {absent} | {absent} | "
                             f"{absent} | {absent} | {absent} | {absent} | {absent} | {legacy(row)} |")
            for slot, viewer in sorted(held["cards"].items()):
                lines.append(f"| {row['run_id']} | PARTIAL | {slot} ({viewer['seat']}, {viewer['model']}) | {cells(viewer['scores'])} | "
                             f"{viewer['first_four_subtotal']} [MEASURED] | {viewer['total']} [MEASURED] | "
                             + ("PASS" if viewer["pass"] else "HOLD: " + ", ".join(viewer["reasons"]))
                             + f" | {absent} (no action contract was bound before these seals) | {legacy(row)} |")
    return "\n".join(lines) + "\n"


