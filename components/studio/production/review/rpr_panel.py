def panel_commands(commands):
    slots = ("blind-ctx", "seal", "card-ctx", "accept", "judge", "observe")
    for name, help_text in (
            ("register", "create the preregistered viewer slots of a pack"),
            ("brief", "bind the intended action and its action contract, released only after sealing"),
            ("technical", "bind the technical verdict of the same bytes"),
            ("blind-ctx", "write the first viewing context"),
            ("seal", "seal a first viewing response"),
            ("card-ctx", "write the scoring card context"),
            ("accept", "accept a scoring card"),
            ("judge", "accept the judgment of the independent judge over a sealed account"),
            ("score", "verify every seal and card again and evaluate the panel"),
            ("jobs", "write the open blind, card and judgment jobs of packs under the rule in force"),
            ("reserve", "register and list the reserve viewer where the primaries split"),
            ("observe", "run one observer call and seal or accept its response"),
            ("drive", "run observer calls from a job list"),
            ("calibrate", "write the canonical axis scores of the registered anchors")):
        parser = commands.add_parser(name, help=help_text)
        parser.add_argument("--root", required=True, help="workspace directory for packs and panel")
        if name in ("jobs", "reserve"):
            parser.add_argument("--out-blind", type=Path, required=True)
            parser.add_argument("--out-card", type=Path, required=True)
            parser.add_argument("--out-match", type=Path, required=True)
            if name == "jobs":
                parser.add_argument("--slots", default="", help="restrict to these slots, comma separated")
            continue
        if name == "calibrate":
            parser.add_argument("--registry", type=Path, required=True)
            parser.add_argument("--out", type=Path, required=True)
            continue
        if name == "drive":
            parser.add_argument("--jobs", type=Path, required=True)
            parser.add_argument("--log", type=Path, required=True)
            parser.add_argument("--limits", default="", help="SEAT=N, comma separated")
            parser.add_argument("--attempts", type=int, default=4)
            parser.add_argument("--format-retries", type=int, default=4,
                                help="new attempts allowed for a response that fails on form")
            parser.add_argument("--adapter", type=Path, help="scripted adapter for tests; never launches a model")
            continue
        parser.add_argument("--pack", type=Path, required=True)
        if name in slots:
            parser.add_argument("--slot", required=True)
        if name in ("blind-ctx", "seal", "observe"):
            parser.add_argument("--segment", type=int)
        if name in ("seal", "accept", "judge"):
            parser.add_argument("--oneshot", type=Path, required=True)
        if name == "brief":
            parser.add_argument("--text", type=Path, required=True)
            parser.add_argument("--contract", type=Path, help="action contract the orchestrator will compare against")
            parser.add_argument("--source", required=True)
        if name == "technical":
            parser.add_argument("--receipt", type=Path, required=True)
        if name == "observe":
            parser.add_argument("kind", choices=("blind", "card", "match"))
            parser.add_argument("--adapter", type=Path)


def dispatch(args):
    root, pack = as_root(args.root), getattr(args, "pack", None)
    verb = args.verb
    if verb == "register":
        return register(pack, root), 0
    if verb == "brief":
        return set_binding(pack, root, "brief", brief_record(pack, root, args.text, args.source, args.contract)), 0
    if verb == "technical":
        return set_binding(pack, root, "technical", technical_record(pack, root, args.receipt)), 0
    if verb == "blind-ctx":
        return ensure_blind_context(pack, root, args.slot, args.segment), 0
    if verb == "card-ctx":
        return ensure_card_context(pack, root, args.slot), 0
    if verb == "seal":
        return seal(pack, root, args.slot, args.segment, args.oneshot), 0
    if verb == "accept":
        return accept(pack, root, args.slot, args.oneshot), 0
    if verb == "judge":
        return judge(pack, root, args.slot, args.oneshot), 0
    if verb == "score":
        return score(pack, root)
    if verb == "jobs":
        labels = {R.pack_id_for(a["movie_sha256"]): a["run_id"] for a in
                  C.read_json(root / "anchors" / "ANCHORS.json")["anchors"]} \
            if (root / "anchors" / "ANCHORS.json").is_file() else {}
        blind, card, match = job_lists(root, [s for s in args.slots.split(",") if s], labels)
        write_jobs(args.out_blind, blind)
        write_jobs(args.out_card, card)
        write_jobs(args.out_match, match)
        return {"status": "JOBS", "blind": len(blind), "card": len(card), "match": len(match),
                "out_blind": str(args.out_blind), "out_card": str(args.out_card), "out_match": str(args.out_match),
                "superseded": [viewers["pack"] for _, viewers in registered_packs(root)
                               if pack_rule(Path(viewers["pack"])) != C.load_protocol()["sampling"]["rule"]]}, 0
    if verb == "reserve":
        blind, card, match = reserve_jobs(root)
        write_jobs(args.out_blind, blind)
        write_jobs(args.out_card, card)
        write_jobs(args.out_match, match)
        return {"status": "RESERVE", "blind": len(blind), "card": len(card), "match": len(match),
                "out_blind": str(args.out_blind), "out_card": str(args.out_card), "out_match": str(args.out_match)}, 0
    if verb == "observe":
        if args.kind == "blind" and args.segment is None:
            raise C.Harness("a blind observation needs --segment")
        return observe({"kind": args.kind, "pack": str(pack), "slot": args.slot, "segment": args.segment},
                       root, args.adapter), 0
    if verb == "drive":
        limits = {seat: int(count) for seat, count in (item.split("=", 1) for item in args.limits.split(",") if item)}
        failures = drive(args.jobs, args.log, limits, args.attempts, root=root, adapter=args.adapter,
                         format_retries=args.format_retries)
        return {"status": "DRIVEN", "failures": failures}, 0 if failures == 0 else 1
    if verb == "calibrate":
        return calibrate(args.registry, args.out, root)
    raise C.Harness(f"unknown panel verb {verb}")
