# ------------------------------------------------------------------ guards
def leak_scan(text, protocol, brief_text=None):
    lowered = text.lower()
    hits = sorted(pattern for pattern in protocol["_terms"] if re.search(pattern, lowered))
    shared = []
    if brief_text:
        words = lambda value: re.findall(r"[a-z0-9']+", value.lower())  # noqa: E731
        haystack = " ".join(words(text))
        source = words(brief_text)
        five_grams = {" ".join(source[at:at + 5]) for at in range(len(source) - 4)}
        shared = sorted(gram for gram in five_grams if gram in haystack)
    return hits, shared


def protocol_with_terms():
    protocol = C.load_protocol()
    protocol["_terms"] = C.read_json(C.PROTOCOL_DIR / "DISCLOSED_TERMS.json")["patterns"]
    return protocol


def check_budget(ctx, task, protocol, label, limit=None):
    ctx_bytes, task_bytes = len(ctx.encode("utf-8")), len(task.encode("utf-8"))
    limit = limit or protocol["context_max_bytes"]
    if task_bytes * protocol["context_task_ratio_min"] > ctx_bytes:
        raise C.Harness(f"{label}: context is smaller than {protocol['context_task_ratio_min']} times the task")
    if ctx_bytes + task_bytes > limit:
        raise C.Harness(f"{label}: context and task exceed {limit} bytes")
    return {"context_bytes": ctx_bytes, "task_bytes": task_bytes, "ratio": round(ctx_bytes / task_bytes, 2)}


# ------------------------------------------------------------------ stage 1
def segment_samples(manifest, protocol, segment):
    segments = plan_segments(manifest, protocol)
    if not 0 <= segment < len(segments):
        raise C.Harness(f"segment {segment} does not exist; the pack has {len(segments)}")
    chosen = segments[segment]
    samples = [s for s in manifest["samples"] if chosen["first_index"] <= s["index"] <= chosen["last_index"]]
    if len(samples) != chosen["count"]:
        raise C.Harness("segment bounds do not match the manifest")
    return segments, chosen, samples


