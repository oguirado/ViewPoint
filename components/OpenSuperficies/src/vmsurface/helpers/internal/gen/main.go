// Command gen extracts Go string constants without importing the surface package.
package main

import (
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
)

func main() {
	if e := run(); e != nil {
		fmt.Fprintln(os.Stderr, e)
		os.Exit(2)
	}
}
func run() error {
	root := flag.String("surface", "../../browserid/surface", "surface sources")
	out := flag.String("out", "helpers_gen.go", "output")
	flag.Parse()
	names := []string{"pastePython", "axPython", "downloadsPython", "recordPython"}
	timeouts := []int{10000, 3000, 18000, 0}
	caps := []int{16384, 32769, 0, -1}
	found := map[string]string{}
	files, e := filepath.Glob(filepath.Join(*root, "*.go"))
	if e != nil {
		return e
	}
	for _, p := range files {
		f, e := parser.ParseFile(token.NewFileSet(), p, nil, 0)
		if e != nil {
			return e
		}
		for _, d := range f.Decls {
			g, ok := d.(*ast.GenDecl)
			if !ok || g.Tok != token.CONST {
				continue
			}
			for _, s := range g.Specs {
				v := s.(*ast.ValueSpec)
				for i, n := range v.Names {
					for _, wanted := range names {
						if n.Name != wanted {
							continue
						}
						if i >= len(v.Values) {
							return fmt.Errorf("missing value %s", wanted)
						}
						lit, ok := v.Values[i].(*ast.BasicLit)
						if !ok || lit.Kind != token.STRING {
							return fmt.Errorf("nonliteral %s", wanted)
						}
						src, e := strconv.Unquote(lit.Value)
						if e != nil {
							return e
						}
						if _, ok := found[wanted]; ok {
							return fmt.Errorf("duplicate %s", wanted)
						}
						found[wanted] = src
					}
				}
			}
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by go generate; DO NOT EDIT.\npackage helpers\n\nvar Entries = [...]Entry{\n")
	for i, n := range names {
		src, ok := found[n]
		if !ok {
			return fmt.Errorf("AUSENTE — helper %s", n)
		}
		fmt.Fprintf(&b, "{%q,%q,%d,%d,%t},\n", n, fmt.Sprintf("%x", sha256.Sum256([]byte(src))), timeouts[i], caps[i], i == 3)
	}
	b.WriteString("}\n")
	data, e := format.Source(b.Bytes())
	if e != nil {
		return e
	}
	return os.WriteFile(*out, data, 0644)
}
