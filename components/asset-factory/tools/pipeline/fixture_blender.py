"""Blender-only procedural witness, also renders a declared GLB for the bench.

Called by the E2E tests in an owned memory scope; never imported by host code.
Output geometry is generated by Blender operators, without third-party assets.
"""
import math
from pathlib import Path
import sys


def main():
    import bpy
    from mathutils import Vector
    args = sys.argv[sys.argv.index("--") + 1:]
    root = Path(args[0])
    root.mkdir(parents=True, exist_ok=True)
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)
    if len(args) > 1:
        bpy.ops.import_scene.gltf(filepath=args[1])
    else:
        bpy.ops.mesh.primitive_cube_add(size=2)
        obj = bpy.context.object
        obj.name = "body"
        obj.scale = (1, 0.65, 0.8)
        bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
        material = bpy.data.materials.new("ochre")
        material.use_nodes = True
        bsdf = material.node_tree.nodes.get("Principled BSDF")
        bsdf.inputs["Base Color"].default_value = (0.35, 0.17, 0.07, 1)
        bsdf.inputs["Roughness"].default_value = 0.6
        obj.data.materials.append(material)
        bpy.ops.export_scene.gltf(filepath=str(root / "prop.glb"), export_format="GLB", use_selection=True)
    scene = bpy.context.scene
    scene.render.engine = "CYCLES"
    scene.cycles.device = "CPU"
    scene.cycles.use_denoising = False
    scene.cycles.samples = 16
    scene.cycles.seed = 42
    scene.render.resolution_x = scene.render.resolution_y = 128
    scene.render.resolution_percentage = 100
    scene.render.film_transparent = True
    scene.render.image_settings.file_format = "PNG"
    scene.render.image_settings.color_mode = "RGBA"
    scene.view_settings.view_transform = "Standard"
    scene.world.use_nodes = True
    scene.world.node_tree.nodes["Background"].inputs["Color"].default_value = (0.3, 0.3, 0.3, 1)
    bpy.ops.object.camera_add(location=(4, -6, 4))
    camera = bpy.context.object
    camera.rotation_euler = (Vector((0, 0, 0)) - camera.location).to_track_quat("-Z", "Y").to_euler()
    camera.data.type = "ORTHO"
    camera.data.ortho_scale = 4
    scene.camera = camera
    bpy.ops.object.light_add(type="AREA", location=(2, -3, 5))
    light = bpy.context.object
    light.data.energy = 350
    light.data.shape = "DISK"
    light.data.size = 4
    light.rotation_euler = (Vector((0, 0, 0)) - light.location).to_track_quat("-Z", "Y").to_euler()
    scene.render.filepath = str(root / "reference.png")
    bpy.ops.render.render(write_still=True)
    if len(args) == 1:
        for obj in list(scene.objects):
            if obj.type == "MESH":
                bpy.data.objects.remove(obj, do_unlink=True)
        bpy.ops.mesh.primitive_uv_sphere_add(segments=16, ring_count=8, radius=0.35)
        scene.render.filepath = str(root / "different.png")
        bpy.ops.render.render(write_still=True)


if __name__ == "__main__":
    main()
