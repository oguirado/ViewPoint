"""Lane H (v12e room HD): the held-out split v2 (test 1000..1029) was CONSUMED by W6 at a66d99e, so X4/X3 bind to the
fresh pre-registered manifest eval/splits/x4_v3.json (test 2000..2029; X4 cal 30..199 = the enlarged H_DEAD fit split;
X3 cal 40..69 = its power check), generated by rendering + hashing only. v2 stays on disk, pinned for audit.
These tests never classify a seed in 1000..1029 or 2000..2029 (render + hash of calibration seeds only)."""
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from eval import splits as SPL, x3_power as X3, x4_fp as X4
from eval.splits import build as B
from tests.px_mutants import driver as D
from visioncore import canon
from visioncore.errors import VqaError

V3_SHA = "5269d68e99d1d421b1ca7b43055ad0c9b0bde812218aabb0176890ba29584b5d"
V2_SHA = "175bf43bdc5b3a60980c4d52325269b8aa904038cc5202a67a5917c4e55b7c28"
TEST = list(range(2000, 2030))


def no_analysis():
    return mock.patch.object(D, "classify_frames", side_effect=AssertionError("analysis ran"))


class SplitV3(unittest.TestCase):
    def test_drivers_pin_v3_and_keep_v2_for_audit(self):
        self.assertEqual((X4.MANIFEST_SHA256, X3.MANIFEST_SHA256), (V3_SHA, V3_SHA))
        self.assertEqual((X4.MANIFEST_V2_SHA256, X3.MANIFEST_V2_SHA256), (V2_SHA, V2_SHA))
        self.assertEqual(SPL.file_sha(SPL.X4_V3), V3_SHA)
        self.assertEqual(SPL.load(SPL.X4_V2, V2_SHA).doc["split_id"], "x4_v2")   # audit copy intact
        with self.assertRaises(VqaError) as cm:
            SPL.load(SPL.X4_V2, X4.MANIFEST_SHA256)                            # v2 no longer the driver pin
        self.assertEqual(cm.exception.detail["why"], "manifest_sha_mismatch")

    def test_partition_fresh_and_disjoint(self):
        m = X4.load_manifest()
        self.assertEqual((m.sha, m.doc["split_id"]), (V3_SHA, "x4_v3"))
        self.assertEqual(m.doc["partition"], {"cal": list(range(30, 200)), "test": TEST, "x3_cal": list(range(40, 70))})
        self.assertEqual(m.config["x4"], {"W": X4.SEAL_W, "H": X4.SEAL_H, "frames": X4.N_FRAMES, "controls": list(X4.CONTROLS)})
        for c in X4.CONTROLS:
            self.assertEqual([k[1] for k in m.keys("x4", "test") if k[0] == c], TEST)
            self.assertEqual([k[1] for k in m.keys("x4", "cal") if k[0] == c], list(range(30, 200)))
        for mu in X3.MUTANTS:
            for lv in range(3):
                self.assertEqual([k[2] for k in m.keys("x3", "test") if k[:2] == (mu, lv)], TEST)
                self.assertEqual([k[2] for k in m.keys("x3", "cal") if k[:2] == (mu, lv)], list(range(40, 70)))
        seeds = {e["seed"] for x in ("x4", "x3") for e in m.doc[x]}
        self.assertFalse(seeds & (set(range(30)) | set(range(1000, 1030))))   # contaminated + consumed never registered
        v2 = SPL.load(SPL.X4_V2, V2_SHA)
        caps = [e["capture_sha256"] for x in ("x4", "x3") for e in m.doc[x]]
        self.assertEqual(len(caps), len(set(caps)))
        v2_test = {e["capture_sha256"] for x in ("x4", "x3") for e in v2.doc[x] if e["split"] == "test"}
        self.assertFalse(v2_test & set(caps))
        self.assertEqual(SPL.X4_V3.read_text(), canon.dumps(m.doc))

    def test_cal_entries_regenerate_without_analysis(self):
        m = X4.load_manifest()
        with no_analysis():
            for c, s in (("iid_noise", 40), ("gpu_jitter", 199)):
                fr = X4.build_control(c, s, X4.SEAL_W, X4.SEAL_H, X4.N_FRAMES)
                m.verify("x4", (c, s), SPL.capture_sha(fr))
            fr, _ = X3.build_trial(X3.trial_spec("shift", 2, 45))
            m.verify("x3", ("shift", 2, 45), SPL.capture_sha(fr))

    def test_entry_points_bind_v3(self):
        for mod in (X4, X3):
            seen = []
            with mock.patch.object(mod, "run_rows", side_effect=lambda s, o, **kw: (seen.append(kw["manifest"].sha), ([], {}))[1]), \
                    no_analysis():
                mod.run(None)
            self.assertEqual(seen, [V3_SHA])

    def test_v2_seed_refused_by_v3_before_render(self):
        m = X4.load_manifest()
        with mock.patch.object(X4, "build_control", side_effect=AssertionError("rendered")), no_analysis():
            for seed in (0, 1000, 1029):
                with self.assertRaises(VqaError) as cm:
                    X4.run_trial("iid_noise", seed, X4.SEAL_W, X4.SEAL_H, X4.N_FRAMES, m)
                self.assertEqual(cm.exception.detail["why"], "unregistered_key")

    def test_generator_split_table_and_tiny_x3_cal(self):
        self.assertEqual(B.SPLITS["x4_v3"]["test_seeds"], tuple(TEST))
        self.assertEqual(B.SPLITS["x4_v2"]["test_seeds"], tuple(range(1000, 1030)))
        tiny4 = {"W": 256, "H": 160, "frames": 16, "controls": ["clean_static"]}
        tiny3 = {"frames": X3.N_FRAMES, "mutants": ["flicker"], "levels": 1}
        with no_analysis():
            doc = B.build((5000,), (30,), tiny4, tiny3, x3_cal_seeds=(41,), split_id="x4_tiny")
        self.assertEqual(doc["split_id"], "x4_tiny")
        self.assertEqual([(e["seed"], e["split"]) for e in doc["x3"]], [(41, "cal"), (5000, "test")])
        with tempfile.TemporaryDirectory() as d:
            p = Path(d) / "m.json"
            p.write_text(canon.dumps(doc))
            self.assertEqual(SPL.load(p).keys("x3", "cal"), [("flicker", 0, 41)])


if __name__ == "__main__":
    unittest.main()
