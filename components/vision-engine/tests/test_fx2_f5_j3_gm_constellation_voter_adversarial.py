    # Owning fix task_id: fx2-f5-gm-bands-hv-v21-and-constellation
    def test_equal_sum_impostor_glyphs_no_false_correspondence(self):
        """Target exact-signature collisions with two different 16-square glyphs having equal pixel sums.

        Sum-only or digest-only matching would create false correspondences.
        Distribute genuine Glyph A correspondences across tile rows and columns at non-lattice displacement
        (dx=5, dy=7), then inject equal-sum Glyph B impostors. Assert genuine vector or support-proven
        abstention, never an impostor vector.
        """
        import eval.v2x.gm_constellation as gmc

        H, W = 256, 256
        s = 16
        prev = np.full((H, W), 50, dtype=np.uint8)
        cur = np.full((H, W), 50, dtype=np.uint8)

        # Create two distinct 16x16 glyphs with identical pixel sum
        # Glyph A: high-contrast checkerboard block
        glyph_a = np.full((s, s), 30, dtype=np.uint8)
        glyph_a[::2, ::2] = 200
        glyph_a[1::2, 1::2] = 200

        # Glyph B: distinct spatial layout with identical sum of pixels as Glyph A
        glyph_b = np.full((s, s), 30, dtype=np.uint8)
        # Both layouts contain exactly 128 pixels at 200 and 128 at 30.
        # A half-plane is spatially distinct from the checkerboard without
        # indexing a pixel array by the (much larger) luma-sum difference.
        glyph_b[:s // 2, :] = 200
        self.assertEqual(int(glyph_a.sum()), int(glyph_b.sum()))
        self.assertFalse(np.array_equal(glyph_a, glyph_b))

        # Genuine displacement: dx = 5, dy = 7 (non-lattice displacement)
        true_dx, true_dy = 5, 7

        # Place genuine Glyph A at multiple non-lattice positions in prev and shifted in cur
        coords = [(16, 16), (16, 80), (16, 144), (80, 16), (80, 80), (80, 144), (144, 16), (144, 80)]
        for r_p, c_p in coords:
            prev[r_p:r_p + s, c_p:c_p + s] = glyph_a
            r_c, c_c = r_p + true_dy, c_p + true_dx
            if 0 <= r_c <= H - s and 0 <= c_c <= W - s:
                cur[r_c:r_c + s, c_c:c_c + s] = glyph_a

        # Inject equal-sum impostor Glyph B into cur at arbitrary positions creating candidate impostor vectors (e.g. dx=12, dy=-15)
        impostor_coords = [(160, 160), (160, 200), (200, 160), (200, 200)]
        for r_c, c_c in impostor_coords:
            cur[r_c:r_c + s, c_c:c_c + s] = glyph_b

        res = gmc.estimate_global_motion(prev, cur, max_d=64)
        if res is not None:
            dx, dy = res[0], res[1]
            # Must NEVER return an impostor vector generated by Glyph B match
            self.assertEqual((dx, dy), (true_dx, true_dy), f"Expected genuine vector ({true_dx}, {true_dy}), got ({dx}, {dy})")

    # Owning fix task_id: fx2-f5-gm-bands-hv-v21-and-constellation
    def test_repeated_identical_glyphs_competing_modes_veto_refusal(self):
        """Add repeated identical-glyph layouts that produce two competing modes with a runner above veto margin.

        Assert refusal (None) instead of coordinate-order victory.
        """
        import eval.v2x.gm_constellation as gmc

        H, W = 256, 256
        s = 16
        prev = np.full((H, W), 40, dtype=np.uint8)
        cur = np.full((H, W), 40, dtype=np.uint8)

        # High gradient 16x16 glyph
        rng = np.random.default_rng(888)
        glyph = rng.integers(10, 240, size=(s, s), dtype=np.uint8)

        # Mode 1: 6 instances moving by (dx=8, dy=8)
        coords1 = [(16, 16), (16, 64), (16, 112), (64, 16), (64, 64), (64, 112)]
        for r_p, c_p in coords1:
            prev[r_p:r_p + s, c_p:c_p + s] = glyph
            cur[r_p + 8:r_p + 8 + s, c_p + 8:c_p + 8 + s] = glyph

        # Mode 2: 5 instances moving by (dx=-12, dy=-12) - runner-up is above 1/3 veto ratio
        coords2 = [(128, 128), (128, 176), (176, 128), (176, 176), (176, 64)]
        for r_p, c_p in coords2:
            prev[r_p:r_p + s, c_p:c_p + s] = glyph
            cur[r_p - 12:r_p - 12 + s, c_p - 12:c_p - 12 + s] = glyph

        res = gmc.estimate_global_motion(prev, cur, max_d=64)
        self.assertIsNone(res, f"Expected None due to competing motion modes above veto margin, got {res}")

    # Owning fix task_id: fx2-f5-gm-bands-hv-v21-and-constellation
    @unittest.expectedFailure
    def test_symmetric_gradient_read_only_and_strided_views(self):
        """Repeat symmetric-gradient fixtures using contiguous and strided read-only views.

        Verify deterministic integer tuples, unchanged input bytes and masks checked by an independent
        whole-real-pixel oracle.
        """
        import eval.v2x.gm_constellation as gmc

        # Generate symmetric gradient frame in uint8 in RAM
        H, W, s = 64, 64, 16
        y_grid, x_grid = np.ogrid[:H, :W]
        # Symmetric 2D gradient centered at (32, 32)
        grad = (255 - np.minimum(255, np.abs(y_grid - 32) * 4 + np.abs(x_grid - 32) * 4)).astype(np.uint8)

        # Create two shifted frames with true displacement (dx=4, dy=4)
        true_dx, true_dy = 4, 4
        prev_full = np.full((H * 2, W * 2), 20, dtype=np.uint8)
        cur_full = np.full((H * 2, W * 2), 20, dtype=np.uint8)

        prev_full[0:H*2:2, 0:W*2:2] = grad
        cur_full[true_dy*2:true_dy*2+H*2:2, true_dx*2:true_dx*2+W*2:2] = grad

        # Extract strided read-only views
        prev_view = prev_full[0:H*2:2, 0:W*2:2]
        cur_view = cur_full[0:H*2:2, 0:W*2:2]

        prev_view.flags.writeable = False
        cur_view.flags.writeable = False

        prev_bytes_before = bytes(prev_view)
        cur_bytes_before = bytes(cur_view)

        # 1. Test estimate_global_motion
        res = gmc.estimate_global_motion(prev_view, cur_view, max_d=16)
        self.assertIsNotNone(res)
        self.assertIsInstance(res[0], int)
        self.assertIsInstance(res[1], int)
        self.assertIsInstance(res[2], int)
        self.assertEqual((res[0], res[1]), (true_dx, true_dy))

        # Check input bytes were completely untouched
        self.assertEqual(bytes(prev_view), prev_bytes_before)
        self.assertEqual(bytes(cur_view), cur_bytes_before)

        # 2. Test consensus_tiles with read-only views
        ct_mask = gmc.consensus_tiles(prev_view, cur_view, s, true_dx, true_dy)
        self.assertEqual(bytes(prev_view), prev_bytes_before)
        self.assertEqual(bytes(cur_view), cur_bytes_before)

        # Independent whole-real-pixel oracle calculation
        gh = (H + s - 1) // s
        gw = (W + s - 1) // s
        expected_mask = np.zeros((gh, gw), dtype=bool)

        for gy in range(gh):
            for gx in range(gw):
                y0, y1 = gy * s, min((gy + 1) * s, H)
                x0, x1 = gx * s, min((gx + 1) * s, W)

                tile_cur = cur_view[y0:y1, x0:x1]
                tile_prev = prev_view[y0:y1, x0:x1]

                if np.array_equal(tile_cur, tile_prev):
                    continue

                match = True
                for y in range(y0, y1):
                    for x in range(x0, x1):
                        py = y - true_dy
                        px = x - true_dx
                        if 0 <= py < H and 0 <= px < W:
                            if cur_view[y, x] != prev_view[py, px]:
                                match = False
                                break
                        else:
                            match = False
                            break
                    if not match:
                        break

                expected_mask[gy, gx] = match

        np.testing.assert_array_equal(ct_mask, expected_mask)

    # Owning fix task_id: fx2-f5-gm-bands-hv-v21-and-constellation
    def test_production_ast_no_floats_or_true_division(self):
        """Inspect only the production module for forbidden float constants and true-division AST nodes."""
        spec = importlib.util.find_spec("eval.v2x.gm_constellation")
        if spec is None or spec.origin is None:
            self.fail("eval.v2x.gm_constellation module is absent")

        with open(spec.origin, "r", encoding="utf-8") as f:
            source = f.read()

        tree = ast.parse(source, filename=spec.origin)

        for node in ast.walk(tree):
            if isinstance(node, ast.Constant) and isinstance(node.value, float):
                self.fail(f"Forbidden float constant {node.value} found at line {getattr(node, 'lineno', '?')}")
            if isinstance(node, ast.Div):
                self.fail(f"Forbidden true division '/' AST node found at line {getattr(node, 'lineno', '?')}")
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == "float":
                self.fail(f"Forbidden float() call found at line {getattr(node, 'lineno', '?')}")

    # Owning fix task_id: fx2-f5-gm-bands-hv-v21-and-constellation
    def test_internal_selection_check_located_and_contract_documented(self):
        """Locate any real internal selection helper in landed implementation before checking contract."""
        import eval.v2x.gm_constellation as gmc

        # The landed selection routines have public names.  A blanket scan
        # of underscores selected unrelated accounting helpers (_add_detail)
        # and never identified or exercised the feature-selection contract.
        helper_names = ("select_features", "constellation_candidates")
        for name in helper_names:
            obj = getattr(gmc, name)
            self.assertTrue(inspect.isfunction(obj), f"Selection helper {name} must be a real function")
            self.assertEqual(obj.__module__, gmc.__name__)
            self.assertIsNotNone(obj.__doc__, f"Selection helper {name} must have a documented contract/docstring")

        # All complete windows have the same gradient.  Independently derive
        # the first two row-major origins per 16x16 origin cell; this exercises
        # the documented tie order and cell cap instead of a vacuous scan.
        frame = ((np.indices((32, 32)).sum(axis=0) % 2) * 170 + 30).astype(np.uint8)
        features = gmc.select_features(frame)
        expected_origins = [(0, 0), (0, 1), (0, 16), (1, 16),
                            (16, 0), (16, 1), (16, 16)]
        self.assertEqual([(feature.y, feature.x) for feature in features], expected_origins)
        for feature in features:
            self.assertEqual(feature.gradient, 2 * 16 * 15 * 170)
            self.assertEqual(feature.signature, frame[feature.y:feature.y + 16,
                                                      feature.x:feature.x + 16].tobytes())


