"""ADV_SEAL1 1 (split leakage): seeds 0..29 were inspected during diagnosis, so G-E2/G-E3 bind to a FRESH pre-registered
manifest eval/splits/x4_v2.json (test 1000..1029, cal 30..39) generated by rendering + hashing only. Drivers load it,
refuse unregistered keys, verify every capture sha before classifying and stamp the manifest sha on every row.
These tests never classify a seed in 1000..1029 (tiny private manifests use seeds 30, 31 and 5000, 5001)."""
import json
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from eval import splits as SPL, x3_power as X3, x4_fp as X4
from eval.splits import build as B
from tests.px_mutants import driver as D
from visioncore import canon
from visioncore.errors import VqaError

TINY4 = {"W": 256, "H": 160, "frames": 16, "controls": ["clean_static", "shader_pulse"]}
TINY3 = {"frames": X3.N_FRAMES, "mutants": ["flicker"], "levels": 1}


def tiny_manifest(d, mutate=None):
    doc = B.build(test_seeds=(5000, 5001), cal_seeds=(30, 31), x4=dict(TINY4), x3=dict(TINY3))
    if mutate:
        mutate(doc)
    p = Path(d) / "m.json"
    p.write_text(canon.dumps(doc))
    return SPL.load(p)


def no_analysis():
    return mock.patch.object(D, "classify_frames", side_effect=AssertionError("analysis ran"))


class SplitCase(unittest.TestCase):
    def leak(self, why=None):
        test = self

        class Ctx:
            def __enter__(self):
                self.cm = test.assertRaises(VqaError)
                self.cm.__enter__()
                return self

            def __exit__(self, *a):
                r = self.cm.__exit__(*a)
                e = self.cm.exception
                test.assertEqual((e.code, e.rc, e.detail["reason"]), ("E_GATE", 5, "split_leak"))
                if why:
                    test.assertEqual(e.detail["why"], why)
                return r
        return Ctx()


class RegisteredManifest(SplitCase):
    def test_pinned_sha_and_partition(self):
        m = SPL.load(SPL.X4_V2, X4.MANIFEST_V2_SHA256)
        self.assertEqual(X3.MANIFEST_V2_SHA256, m.sha)
        self.assertEqual(m.doc["partition"], {"cal": list(range(30, 40)), "test": list(range(1000, 1030))})
        self.assertEqual(m.config["x4"], {"W": X4.SEAL_W, "H": X4.SEAL_H, "frames": X4.N_FRAMES, "controls": list(X4.CONTROLS)})
        for c in X4.CONTROLS:
            self.assertEqual([k[1] for k in m.keys("x4", "test") if k[0] == c], list(range(1000, 1030)))
            self.assertEqual([k[1] for k in m.keys("x4", "cal") if k[0] == c], list(range(30, 40)))
        for mu in X3.MUTANTS:
            for lv in range(3):
                self.assertEqual([k[2] for k in m.keys("x3", "test") if k[:2] == (mu, lv)], list(range(1000, 1030)))
        seeds = {e["seed"] for x in ("x4", "x3") for e in m.doc[x]}
        self.assertFalse(seeds & set(range(30)))   # the contaminated test seeds are not registered at all
        caps = [e["capture_sha256"] for x in ("x4", "x3") for e in m.doc[x]]
        self.assertEqual(len(caps), len(set(caps)))
        self.assertEqual(m.doc["x4"], sorted(m.doc["x4"], key=lambda e: (e["control"], e["seed"])))
        self.assertEqual(SPL.X4_V2.read_text(), canon.dumps(m.doc))   # canonical bytes

    def test_cal_entry_regenerates(self):
        # rendering + hashing only (calibration seed), never the held-out seeds
        m = X4.load_manifest()
        with no_analysis():
            fr = X4.build_control("iid_noise", 30, X4.SEAL_W, X4.SEAL_H, X4.N_FRAMES)
            m.verify("x4", ("iid_noise", 30), SPL.capture_sha(fr))

    def test_wrong_pin_or_absent_refused(self):
        with self.leak("manifest_sha_mismatch"):
            SPL.load(SPL.X4_V2, "0" * 64)
        with self.leak("manifest_absent"):
            SPL.load(Path(tempfile.gettempdir()) / "no_such_split_manifest.json")

    def test_driver_entry_points_bind_pinned_manifest(self):
        seen = {}

        def fake(seeds, out_dir, **kw):
            seen[kw["manifest"].sha] = True
            return [], {"verdict": "FAIL"}
        for mod in (X4, X3):
            seen.clear()
            with mock.patch.object(mod, "run_rows", side_effect=fake), no_analysis():
                mod.run(None)
            self.assertEqual(list(seen), [X4.MANIFEST_SHA256])


class GeneratorIsBlind(SplitCase):
    def test_build_never_classifies_and_is_deterministic(self):
        with tempfile.TemporaryDirectory() as d, no_analysis():
            a = tiny_manifest(d)
            b = B.build(test_seeds=(5000, 5001), cal_seeds=(30, 31), x4=dict(TINY4), x3=dict(TINY3))
        self.assertEqual(canon.dumps(a.doc), canon.dumps(b))
        self.assertEqual(len(a.doc["x4"]), 8)
        self.assertEqual(len(a.doc["x3"]), 2)

    def test_loader_refuses_overlapping_splits(self):
        def same_cap(doc):
            doc["x4"][-1]["capture_sha256"] = doc["x4"][0]["capture_sha256"]   # test entry reusing a cal capture
        def same_seed(doc):
            doc["x4"].append(dict(doc["x4"][0], split="test" if doc["x4"][0]["split"] == "cal" else "cal",
                                  control="gpu_jitter", capture_sha256="e" * 64))
        with tempfile.TemporaryDirectory() as d:
            with self.leak("duplicate_capture"):
                tiny_manifest(d, same_cap)
            with self.leak("seed_in_both_splits"):
                tiny_manifest(d, same_seed)


class X4Binding(SplitCase):
    def test_registered_rows_carry_manifest(self):
        with tempfile.TemporaryDirectory() as d:
            m = tiny_manifest(d)
            rows, summ = X4.run_rows(30, d, manifest=m)
            self.assertEqual(len(rows), 4)
            self.assertTrue(all(r["manifest_sha256"] == m.sha and r["split"] == "test" for r in rows))
            self.assertEqual(sorted({r["seed"] for r in rows}), [5000, 5001])
            self.assertEqual((summ["manifest_sha256"], summ["sample_complete"], summ["verdict"]), (m.sha, False, "FAIL"))
            line = json.loads((Path(d) / "X4.jsonl").read_text().splitlines()[0])
            self.assertEqual(line["manifest_sha256"], m.sha)
            cal, s2 = X4.run_rows(30, None, manifest=m, split="cal")
            self.assertEqual(({r["seed"] for r in cal}, {r["split"] for r in cal}, s2), ({30, 31}, {"cal"}, None))

    def test_unregistered_seed_refused_before_render(self):
        with tempfile.TemporaryDirectory() as d:
            m = tiny_manifest(d)
            with mock.patch.object(X4, "build_control", side_effect=AssertionError("rendered")), no_analysis():
                for seed in (0, 29, 1000):
                    with self.leak("unregistered_key"):
                        X4.run_trial("clean_static", seed, TINY4["W"], TINY4["H"], TINY4["frames"], m)
                with self.leak("config_not_registered"):
                    X4.run_trial("clean_static", 5000, X4.SEAL_W, X4.SEAL_H, X4.N_FRAMES, m)

    def test_capture_mismatch_refused_before_analysis(self):
        def tamper(doc):
            doc["x4"][0]["capture_sha256"] = "a" * 64
        with tempfile.TemporaryDirectory() as d:
            m = tiny_manifest(d, tamper)
            c, s = m.doc["x4"][0]["control"], m.doc["x4"][0]["seed"]
            with no_analysis(), self.leak("capture_sha_mismatch"):
                X4.run_trial(c, s, TINY4["W"], TINY4["H"], TINY4["frames"], m)

    def test_summary_refuses_unbound_rows(self):
        with tempfile.TemporaryDirectory() as d:
            m = tiny_manifest(d)
            rows, _ = X4.run_rows(30, None, manifest=m)
            cal, _ = X4.run_rows(30, None, manifest=m, split="cal")
            legacy = X4.run_trial("clean_static", 0, TINY4["W"], TINY4["H"], TINY4["frames"])
            with self.leak("manifest_sha_mismatch"):
                X4.summarize_manifest(rows + [legacy], m)
            with self.leak("not_test_seed"):
                X4.summarize_manifest(rows + cal[:1], m)
            with self.leak("duplicate_row"):
                X4.summarize_manifest(rows + rows[:1], m)
            with self.leak("capture_sha_mismatch"):
                X4.summarize_manifest([dict(rows[0], capture_sha256=rows[1]["capture_sha256"])], m)
            with self.leak("unregistered_key"):
                X4.summarize_manifest([dict(rows[0], seed=12)], m)


class X3Binding(SplitCase):
    def test_registered_trial_and_refusals(self):
        def tamper(doc):
            doc["x3"][1]["capture_sha256"] = "b" * 64
        with tempfile.TemporaryDirectory() as d:
            m = tiny_manifest(d)
            rows, summ = X3.run_rows(30, None, manifest=m)
            self.assertEqual([(r["seed"], r["manifest_sha256"], r["split"]) for r in rows],
                             [(5000, m.sha, "test"), (5001, m.sha, "test")])
            self.assertTrue(summ["sample_complete"])
            self.assertEqual(summ["manifest_sha256"], m.sha)
            with mock.patch.object(X3, "build_trial", side_effect=AssertionError("rendered")), self.leak("unregistered_key"):
                X3.run_trial(X3.trial_spec("flicker", 0, 0), m)
            legacy = X3.run_trial(X3.trial_spec("flicker", 0, 30))
            with self.leak("manifest_sha_mismatch"):
                X3.summarize_manifest(rows + [legacy], m)
            with self.leak("duplicate_row"):
                X3.summarize_manifest(rows + rows[:1], m)
            mt = tiny_manifest(d, tamper)
            with no_analysis(), self.leak("capture_sha_mismatch"):
                X3.run_trial(X3.trial_spec("flicker", 0, 5001), mt)


