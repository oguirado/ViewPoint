"""Research prototype for problem P6: finite-partition histogram embeddings.

Separates occlusion or full replacement from deformation using random partitions of luma space.

Method:
For two tiles with pixel token lists L and L' of size s:
- Draw K seeded random partitions of luma space whose collision probability for values u and v is
  exp(-alpha * |u - v|), implemented as randomly shifted grids with exponential cell widths.
- T equals the mean over partitions of the L1 distance of part-count histograms.
- Paper bounds:
  - Upper bound: T <= 2 * t + 2 * alpha * sum(d_m)
    where t is the unpaired count and d_m = |u_m - v_m| are paired element distances.
  - Lower bound: T >= 2 * s * (1 - s^2 * exp(-alpha * a))
    for full replacement with cross distance at least a.
- Classify a changed tile as "OCCLUDE" when T / (2 * s) exceeds a threshold (e.g. 0.5) and as "DEFORM" otherwise.

Standard library and NumPy only.
"""

import numpy as np


def generate_partitions(K, alpha, seed=42, min_val=0.0, max_val=255.0):
    """Generate K random partitions of luma space [min_val, max_val].

    Each partition is a 1D array of partition cut points generated by drawing
    cell widths W ~ Exp(scale = 1 / alpha) starting from a shifted origin.

    Args:
        K (int): Number of partitions to draw.
        alpha (float): Scaling factor alpha > 0.
        seed (int): Seed for reproducibility.
        min_val (float): Minimum expected luma value.
        max_val (float): Maximum expected luma value.

    Returns:
        list of np.ndarray: List of length K containing 1D sorted arrays of partition cut points.
    """
    if alpha <= 0:
        raise ValueError("alpha must be positive")
    if K <= 0:
        raise ValueError("K must be positive")

    rng = np.random.default_rng(seed)
    scale = 1.0 / alpha
    partitions = []

    for _ in range(K):
        # Shifted origin before min_val
        start = min_val - rng.exponential(scale)
        cuts = [start]
        while cuts[-1] <= max_val:
            cuts.append(cuts[-1] + rng.exponential(scale))
        partitions.append(np.array(cuts, dtype=np.float64))

    return partitions


def histogram_embedding_distance(L, L_prime, alpha=0.05, K=200, seed=42):
    """Calculate finite-partition histogram embedding distance T between token lists L and L'.

    Args:
        L (array-like): Token list L of size s (luma values).
        L_prime (array-like): Token list L' of size s (luma values).
        alpha (float): Exponential partition scale parameter.
        K (int): Number of random partitions.
        seed (int): Random seed for partition generation.

    Returns:
        float: Expected L1 distance T between histogram embeddings across K partitions.
    """
    L_arr = np.asarray(L, dtype=np.float64).ravel()
    L_p_arr = np.asarray(L_prime, dtype=np.float64).ravel()

    if len(L_arr) != len(L_p_arr):
        raise ValueError("Token lists L and L_prime must have equal size s")

    s = len(L_arr)
    if s == 0:
        return 0.0

    min_val = min(float(np.min(L_arr)), float(np.min(L_p_arr)))
    max_val = max(float(np.max(L_arr)), float(np.max(L_p_arr)))

    partitions = generate_partitions(K, alpha, seed=seed, min_val=min_val, max_val=max_val)

    total_l1 = 0.0
    for cuts in partitions:
        cells_L = np.searchsorted(cuts, L_arr, side="right")
        cells_L_p = np.searchsorted(cuts, L_p_arr, side="right")

        max_cell = max(int(np.max(cells_L)), int(np.max(cells_L_p)))
        hist_L = np.bincount(cells_L, minlength=max_cell + 1)
        hist_L_p = np.bincount(cells_L_p, minlength=max_cell + 1)

        total_l1 += float(np.sum(np.abs(hist_L - hist_L_p)))

    return total_l1 / float(K)


def upper_bound(t, paired_distances, alpha):
    """Calculate the screened paper upper bound for histogram embedding distance T.

    T <= 2 * t + 2 * alpha * sum(paired_distances)

    Args:
        t (int): Number of unpaired tokens.
        paired_distances (array-like): Distances |u_m - v_m| for paired tokens.
        alpha (float): Partition scale parameter alpha.

    Returns:
        float: Upper bound value for T.
    """
    d_sum = float(np.sum(paired_distances)) if len(paired_distances) > 0 else 0.0
    return 2.0 * float(t) + 2.0 * float(alpha) * d_sum


def lower_bound(s, a, alpha):
    """Calculate the screened paper lower bound for full replacement.

    T >= 2 * s * (1 - s^2 * exp(-alpha * a))

    Args:
        s (int): Token list size.
        a (float): Minimum cross-distance between replaced content.
        alpha (float): Partition scale parameter.

    Returns:
        float: Lower bound value for T.
    """
    return 2.0 * float(s) * (1.0 - (float(s) ** 2) * np.exp(-float(alpha) * float(a)))


def classify_tile_change(L, L_prime, threshold=0.5, alpha=0.05, K=200, seed=42):
    """Classify a changed tile as OCCLUDE or DEFORM based on normalized embedding distance T / (2 * s).

    Args:
        L (array-like): Original tile pixel luma values.
        L_prime (array-like): Changed tile pixel luma values.
        threshold (float): Decision threshold for T / (2 * s) (default 0.5).
        alpha (float): Exponential partition scale parameter.
        K (int): Number of random partitions.
        seed (int): Random seed.

    Returns:
        tuple: (label, normalized_T, T)
            label (str): "OCCLUDE" if T / (2 * s) > threshold, else "DEFORM".
            normalized_T (float): T / (2 * s).
            T (float): Raw histogram embedding distance.
    """
    s = len(np.asarray(L).ravel())
    if s == 0:
        return "DEFORM", 0.0, 0.0

    T = histogram_embedding_distance(L, L_prime, alpha=alpha, K=K, seed=seed)
    norm_T = T / (2.0 * float(s))
    label = "OCCLUDE" if norm_T > threshold else "DEFORM"

    return label, norm_T, T
