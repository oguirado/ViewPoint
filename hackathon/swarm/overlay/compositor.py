    rlw, rlh = _text_size(draw, ring_label, fonts.strip_small)
    if cur_x + rlw < max_ring_x:
        rl_ty = pill_top + ((pill_bot - pill_top) - rlh) // 2
        draw.text((cur_x, rl_ty), ring_label, font=fonts.strip_small, fill=(148, 163, 184, 245))
        cur_x += rlw + max(6, round(8 * scale))

    arrow_str = "->"
    aw, ah = _text_size(draw, arrow_str, fonts.strip_small)
    p_in_pad = max(6, round(9 * scale))
    s_dot_r = max(3, round(4 * scale))

    for idx, ag in enumerate(ring_agents):
        ag_spec = AGENT_SPECS.get(ag, {"rgb": (203, 213, 225)})
        ag_rgb = ag_spec["rgb"]
        q_len = len(tracker.pending_fifo.get(ag) or ())
        is_parked = ag in tracker.parked_agents
        pill_label = f"{ag} [PARK]" if is_parked else (f"{ag} ({q_len})" if q_len > 0 else ag)
        tw, th = _text_size(draw, pill_label, fonts.strip_small)
        pill_w = p_in_pad + 2 * s_dot_r + max(4, round(6 * scale)) + tw + p_in_pad
        needed = pill_w + (aw + max(8, round(10 * scale)) if idx < len(ring_agents) - 1 else 0)
        if cur_x + pill_w > max_ring_x:
            break

        border_rgba = (251, 191, 36, 220) if is_parked else ((*ag_rgb, 210) if q_len > 0 else (71, 85, 105, 190))
        fill_rgba = (30, 41, 59, 232) if q_len > 0 else (20, 29, 45, 205)
        draw.rounded_rectangle(
            [cur_x, pill_top + max(1, round(2 * scale)), cur_x + pill_w, pill_bot - max(1, round(2 * scale))],
            radius=max(4, round(6 * scale)),
            fill=fill_rgba,
            outline=border_rgba,
            width=1,
        )
        dcx = cur_x + p_in_pad + s_dot_r
        dcy = (pill_top + pill_bot) // 2
        draw.ellipse([dcx - s_dot_r, dcy - s_dot_r, dcx + s_dot_r, dcy + s_dot_r], fill=(*ag_rgb, 255))
        ty = pill_top + ((pill_bot - pill_top) - th) // 2 - max(0, round(1 * scale))
        txt_fg = (241, 245, 249, 255) if q_len > 0 else (203, 213, 225, 235)
        draw.text((dcx + s_dot_r + max(4, round(6 * scale)), ty), pill_label, font=fonts.strip_small, fill=txt_fg)
        cur_x += pill_w

        if idx < len(ring_agents) - 1 and cur_x + aw + max(8, round(12 * scale)) <= max_ring_x:
            gap = max(4, round(6 * scale))
            cur_x += gap
            aty = pill_top + ((pill_bot - pill_top) - ah) // 2
            draw.text((cur_x, aty), arrow_str, font=fonts.strip_small, fill=(148, 163, 184, 230))
            cur_x += aw + gap

    return np.asarray(img, dtype=np.uint8)


