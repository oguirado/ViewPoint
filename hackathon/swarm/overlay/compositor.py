def parse_hex_rgb(color_str: Optional[str], fallback: Tuple[int, int, int]) -> Tuple[int, int, int]:
    """Parse `#rrggbb` hex color string into `(R, G, B)` tuple."""
    if not color_str or not isinstance(color_str, str):
        return fallback
    s = color_str.strip().lstrip("#")
    if len(s) == 6:
        try:
            return (int(s[0:2], 16), int(s[2:4], 16), int(s[4:6], 16))
        except ValueError:
            return fallback
    return fallback


