    head_agent = tracker.active_head or "IDLE"
    head_spec = AGENT_SPECS.get(head_agent)
    head_rgb = head_spec["rgb"] if head_spec else (148, 163, 184)
    head_text = f"TURN #{tracker.turn_num} | TICK #{tracker.tick_num} | HEAD: {head_agent} [{tracker.active_lane}]"
    hw, hh = _text_size(draw, head_text, fonts.strip_bold)
    dot_r = max(3, round(5 * scale))
    h_pad = max(8, round(12 * scale))
    h_x0 = pad_x
    h_x1 = min(v_x0 - pad_x, h_x0 + h_pad + (2 * dot_r) + max(6, round(8 * scale)) + hw + h_pad)

    draw.rounded_rectangle(
        [h_x0, pill_top, h_x1, pill_bot],
        radius=pill_r,
        fill=(30, 41, 59, 245),
        outline=(*head_rgb, 245),
        width=max(1, round(2 * scale)),
    )
    dot_cx = h_x0 + h_pad + dot_r
    dot_cy = (pill_top + pill_bot) // 2
    draw.ellipse([dot_cx - dot_r, dot_cy - dot_r, dot_cx + dot_r, dot_cy + dot_r], fill=(*head_rgb, 255))
    h_ty = pill_top + ((pill_bot - pill_top) - hh) // 2 - max(0, round(1 * scale))
    draw.text((dot_cx + dot_r + max(6, round(8 * scale)), h_ty), head_text, font=fonts.strip_bold, fill=(248, 250, 252, 255))

