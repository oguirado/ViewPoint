def render_cursor_patch(
    cstate: CursorVisualState,
    sx: float,
    sy: float,
    scale: float,
    video_rel_ms: float,
    frame_w: int,
    frame_h: int,
    strip_h: int,
    fonts: FontPack,
) -> Tuple[np.ndarray, int, int]:
    """Render one agent's cursor + phase ring + label pill on a tight local RGBA patch."""
    tip_x = int(round(cstate.x * sx))
    tip_y = int(round(cstate.y * sy))
    rgb = cstate.rgb

    # Build phase tag text
    detail = ""
    if ":" in cstate.label:
        _, after = cstate.label.split(":", 1)
        after = after.strip()
        if after and after != cstate.agent_id:
            detail = f" · {after[:24]}"

    if cstate.phase == "intent":
        phase_tag = f"{cstate.agent_id} [intent]{detail}"
    elif cstate.phase == "act":
        phase_tag = f"{cstate.agent_id} [ACTING]{detail}"
    elif cstate.phase == "result":
        v_str = cstate.verdict or "DONE"
        _, _, _, sym = verdict_palette(cstate.verdict or "VERIFIED")
        reb = " REBASED" if cstate.rebased else ""
        phase_tag = f"{cstate.agent_id} [{sym} {v_str}{reb}]"
    else:
        phase_tag = cstate.agent_id

    dummy = Image.new("RGBA", (8, 8), (0, 0, 0, 0))
    d0 = ImageDraw.Draw(dummy)
    tw, th = _text_size(d0, phase_tag, fonts.cursor_bold)

    margin = max(28, round(38 * scale))
    pill_pad_x = max(7, round(10 * scale))
    pill_pad_y = max(3, round(5 * scale))
    pill_w = tw + 2 * pill_pad_x
    pill_h = th + 2 * pill_pad_y

    # Choose label placement (default bottom-right of pointer; flip left/up near screen edges)
    offset_x = max(12, round(16 * scale))
    offset_y = max(12, round(18 * scale))
    place_left = (tip_x + offset_x + pill_w + 12) > frame_w
    place_up = (tip_y + offset_y + pill_h + 44) > frame_h or (tip_y < strip_h + margin and False)

    rel_pill_x = -(offset_x + pill_w) if place_left else offset_x
    rel_pill_y = -(offset_y + pill_h) if place_up else offset_y
    if tip_y + rel_pill_y < strip_h + 4:
        rel_pill_y = max(4, (strip_h + 4) - tip_y)

    min_rx = min(-margin, rel_pill_x - 4)
    max_rx = max(margin, rel_pill_x + pill_w + 4)
    min_ry = min(-margin, rel_pill_y - 4)
    max_ry = max(margin, rel_pill_y + pill_h + 4)

    pw = max_rx - min_rx
    ph = max_ry - min_ry
    cx = -min_rx
    cy = -min_ry

    img = Image.new("RGBA", (pw, ph), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)

    # 1. Phase-specific rings around pointer tip `(cx, cy)`
    if cstate.phase == "intent":
        ring_r = max(12, round(19 * scale))
        halo_r = max(7, round(10 * scale))
        draw.ellipse([cx - halo_r, cy - halo_r, cx + halo_r, cy + halo_r], fill=(*rgb, 48))
        bbox = [cx - ring_r, cy - ring_r, cx + ring_r, cy + ring_r]
        for seg in range(8):
            a0 = seg * 45 + 5
            a1 = a0 + 26
            draw.arc(bbox, start=a0, end=a1, fill=(*rgb, 225), width=max(2, round(2.5 * scale)))

    elif cstate.phase == "act":
        pulse_u = (video_rel_ms % 600.0) / 600.0
        pulse_r = max(10, round((13.0 + 16.0 * pulse_u) * scale))
        pulse_alpha = int(round(230.0 * (1.0 - 0.72 * pulse_u)))
        inner_r = max(6, round(9 * scale))
        draw.ellipse(
            [cx - pulse_r, cy - pulse_r, cx + pulse_r, cy + pulse_r],
            outline=(*rgb, pulse_alpha),
            width=max(2, round(3 * scale)),
        )
        draw.ellipse(
            [cx - inner_r, cy - inner_r, cx + inner_r, cy + inner_r],
            fill=(*rgb, 90),
            outline=(255, 255, 255, 235),
            width=max(1, round(1.5 * scale)),
        )

    elif cstate.phase == "result":
        ring_r = max(9, round(13 * scale))
        _, v_border, _, sym = verdict_palette(cstate.verdict or "VERIFIED")
        draw.ellipse(
            [cx - ring_r, cy - ring_r, cx + ring_r, cy + ring_r],
            fill=(*rgb, 60),
            outline=v_border,
            width=max(2, round(2.5 * scale)),
        )

    # 2. Crisp vector pointer arrow polygon at `(cx, cy)`
    arrow_scale = max(0.65, scale)
    raw_poly = [
        (0.0, 0.0),
        (0.0, 21.0),
        (5.5, 16.2),
        (9.8, 24.5),
        (13.2, 22.8),
        (8.8, 14.5),
        (15.8, 14.5),
    ]
    shadow_pts = [(cx + round(px * arrow_scale) + 1, cy + round(py * arrow_scale) + 2) for px, py in raw_poly]
    arrow_pts = [(cx + round(px * arrow_scale), cy + round(py * arrow_scale)) for px, py in raw_poly]

    ptr_alpha = 165 if cstate.phase == "intent" else (195 if cstate.phase == "idle" else 255)
    outline_alpha = 195 if cstate.phase == "intent" else 250
    draw.polygon(shadow_pts, fill=(8, 12, 22, min(180, ptr_alpha)))
    draw.polygon(arrow_pts, fill=(*rgb, ptr_alpha), outline=(255, 255, 255, outline_alpha))
    draw.line(arrow_pts + [arrow_pts[0]], fill=(255, 255, 255, outline_alpha), width=max(1, round(1.6 * scale)))

    # 3. Result badge icon next to pointer tip when phase == "result"
    if cstate.phase == "result":
        b_bg, b_border, b_fg, sym = verdict_palette(cstate.verdict or "VERIFIED")
        br = max(7, round(9.5 * scale))
        bcx = cx + round(20 * arrow_scale)
        bcy = cy - round(6 * arrow_scale)
        draw.ellipse([bcx - br, bcy - br, bcx + br, bcy + br], fill=b_bg, outline=b_border, width=max(1, round(1.5 * scale)))
        sbbox = draw.textbbox((0, 0), sym, font=fonts.strip_small)
        sw = sbbox[2] - sbbox[0]
        sh = sbbox[3] - sbbox[1]
        draw.text((bcx - sw / 2.0 - sbbox[0], bcy - sh / 2.0 - sbbox[1]), sym, font=fonts.strip_small, fill=b_fg)

    # 4. Agent label pill
    px0 = cx + rel_pill_x
    py0 = cy + rel_pill_y
    px1 = px0 + pill_w
    py1 = py0 + pill_h

    if cstate.phase == "act":
        pill_bg = (15, 23, 42, 245)
        pill_border = (*rgb, 255)
        text_fg = (255, 255, 255, 255)
        b_width = max(2, round(2 * scale))
    elif cstate.phase == "result":
        v_bg, v_border, v_fg, _ = verdict_palette(cstate.verdict or "VERIFIED")
        pill_bg = v_bg
        pill_border = v_border
        text_fg = v_fg
        b_width = max(1, round(2 * scale))
    elif cstate.phase == "intent":
        pill_bg = (15, 23, 42, 210)
        pill_border = (*rgb, 210)
        text_fg = (*rgb, 245)
        b_width = 1
    else:
        pill_bg = (15, 23, 42, 196)
        pill_border = (*rgb, 175)
        text_fg = (226, 232, 240, 235)
        b_width = 1

    draw.rounded_rectangle(
        [px0, py0, px1, py1],
        radius=max(4, round(7 * scale)),
        fill=pill_bg,
        outline=pill_border,
        width=b_width,
    )
    ty = py0 + (pill_h - th) // 2 - max(0, round(1 * scale))
    draw.text((px0 + pill_pad_x, ty), phase_tag, font=fonts.cursor_bold, fill=text_fg)

    return (np.asarray(img, dtype=np.uint8), tip_x + min_rx, tip_y + min_ry)


def _drain_stream(stream: Any, chunks: List[bytes], max_bytes: int = 262144) -> None:
    """Continuously drain a subprocess pipe so it never fills the OS pipe buffer."""
    read_fn = getattr(stream, "read1", stream.read)
    total = 0
    try:
        while True:
            chunk = read_fn(4096)
            if not chunk:
                break
            chunks.append(chunk)
            total += len(chunk)
            while total > max_bytes and len(chunks) > 1:
                dropped = chunks.pop(0)
                total -= len(dropped)
    finally:
        try:
            stream.close()
        except OSError:
            pass


def compose_video(
    input_path: Path,
    events_path: Path,
    output_path: Path,
    start_ts_ms: Optional[int] = None,
    end_ts_ms: Optional[int] = None,
    sidecar_path: Optional[Path] = None,
    timeline_mode: str = "auto",
    lerp_ms: float = DEFAULT_LERP_MS,
    crf: int = 20,
    preset: str = "veryfast",
    strict: bool = False,
) -> Dict[str, Any]:
    """Post-process `input_path` + `events_path` into H.264 `output_path` off-display."""
    os.environ.pop("DISPLAY", None)
    os.environ.pop("WAYLAND_DISPLAY", None)

    if not input_path.is_file():
        raise FileNotFoundError(f"Input video not found: {input_path}")
    if not events_path.is_file():
        raise FileNotFoundError(f"Events JSONL not found: {events_path}")

    output_path.parent.mkdir(parents=True, exist_ok=True)

    meta = probe_video(input_path)
    events = load_events(events_path, strict=strict)
    tl_start, tl_end, tl_source = resolve_timeline(
        input_path=input_path,
        video_meta=meta,
        events=events,
        start_ts_ms=start_ts_ms,
        end_ts_ms=end_ts_ms,
        sidecar_path=sidecar_path,
        timeline_mode=timeline_mode,
    )

    # H.264 yuv420p requires even width & height
    out_w = meta.width if meta.width % 2 == 0 else meta.width - 1
    out_h = meta.height if meta.height % 2 == 0 else meta.height - 1
    sx = out_w / float(CANONICAL_WIDTH)
    sy = out_h / float(CANONICAL_HEIGHT)
    scale = min(sx, sy)
    strip_h = max(28, int(round(TOP_STRIP_HEIGHT * sy)))

    tl_span = float(max(1, tl_end - tl_start))
    vid_dur = float(max(1, meta.duration_ms))
    time_scale = tl_span / vid_dur
    lerp_ts_ms = max(1.0, float(lerp_ms) * time_scale)

    fonts = FontPack(scale=scale)
    tracker_events = filter_events_for_timeline(events, tl_start, tl_source)
    tracker = BrokerTimelineTracker(tracker_events)
    caption_rgba = render_caption_rgba(scale=scale, fonts=fonts)
    cap_x = out_w - caption_rgba.shape[1] - max(8, round(16 * sx))
    cap_y = out_h - caption_rgba.shape[0] - max(6, round(12 * sy))

    strip_cache_key: Optional[Tuple[Any, ...]] = None
    strip_rgba: Optional[np.ndarray] = None

    cap = cv2.VideoCapture(str(input_path))
    if not cap.isOpened():
        raise RuntimeError(f"cv2.VideoCapture failed to open {input_path}")

    ffmpeg_cmd = [
        "ffmpeg",
        "-y",
        "-nostats",
        "-loglevel",
        "error",
        "-f",
        "rawvideo",
        "-vcodec",
        "rawvideo",
        "-pix_fmt",
        "bgr24",
        "-s",
        f"{out_w}x{out_h}",
        "-r",
        f"{meta.fps:.6f}",
        "-i",
        "-",
        "-an",
        "-c:v",
        "libx264",
        "-preset",
        preset,
        "-crf",
        str(crf),
        "-pix_fmt",
        "yuv420p",
        "-movflags",
        "+faststart",
        str(output_path),
    ]

    encoder = subprocess.Popen(
        ffmpeg_cmd,
        stdin=subprocess.PIPE,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.PIPE,
    )

    stderr_chunks: List[bytes] = []
    stderr_thread: Optional[threading.Thread] = None
    if encoder.stderr is not None:
        stderr_thread = threading.Thread(
            target=_drain_stream,
            args=(encoder.stderr, stderr_chunks),
            name="ffmpeg-stderr-drain",
            daemon=True,
        )
        stderr_thread.start()

    frames_written = 0
    agent_render_order = list(RING_ORDER) + [
        aid for aid in tracker.cursors_by_agent.keys() if aid not in RING_ORDER
    ]

    try:
        while True:
            ok, frame = cap.read()
            if not ok or frame is None:
                break
            if frame.shape[1] != out_w or frame.shape[0] != out_h:
                frame = cv2.resize(frame, (out_w, out_h), interpolation=cv2.INTER_AREA)

            video_rel_ms = (frames_written / max(1.0, meta.fps)) * 1000.0
            if meta.nb_frames > 1:
                progress = min(1.0, frames_written / float(max(1, meta.nb_frames - 1)))
            else:
                progress = 0.0

            if tl_source == "span":
                cur_ts_ms = float(tl_start) + progress * tl_span
            else:
                cur_ts_ms = float(tl_start) + video_rel_ms * time_scale

            tracker.advance_to(cur_ts_ms)

            # 1. Render per-agent cursors (draw active head last so it sits on top)
            ordered_agents = [a for a in agent_render_order if a != tracker.active_head]
            if tracker.active_head and tracker.active_head in agent_render_order:
                ordered_agents.append(tracker.active_head)

            for aid in ordered_agents:
                cstate = evaluate_agent_cursor(
                    agent_id=aid,
                    cursor_events=tracker.cursors_by_agent.get(aid) or (),
                    cursor_ts_list=tracker.cursor_ts_by_agent.get(aid) or (),
                    cur_ts_ms=cur_ts_ms,
                    lerp_ts_ms=lerp_ts_ms,
                    close_by_event=tracker.close_by_event,
                )
                patch_rgba, px0, py0 = render_cursor_patch(
                    cstate=cstate,
                    sx=sx,
                    sy=sy,
                    scale=scale,
                    video_rel_ms=video_rel_ms,
                    frame_w=out_w,
                    frame_h=out_h,
                    strip_h=strip_h,
                    fonts=fonts,
                )
                _blend_rgba_patch(frame, patch_rgba, px0, py0)

            # 2. Top Turn-Queue Strip (cached across identical broker states)
            cur_key = tracker.strip_cache_key()
            if strip_rgba is None or cur_key != strip_cache_key:
                strip_rgba = render_top_strip_rgba(
                    width=out_w,
                    strip_h=strip_h,
                    scale=scale,
                    fonts=fonts,
                    tracker=tracker,
                )
                strip_cache_key = cur_key
            _blend_rgba_patch(frame, strip_rgba, 0, 0)

            # 3. Standing attribution caption (bottom-right)
            _blend_rgba_patch(frame, caption_rgba, cap_x, cap_y)

            assert encoder.stdin is not None
            try:
                encoder.stdin.write(frame.tobytes())
            except BrokenPipeError:
                break
            frames_written += 1
    finally:
        cap.release()
        if encoder.stdin is not None:
            try:
                encoder.stdin.close()
            except (BrokenPipeError, OSError):
                pass
        if stderr_thread is not None:
            stderr_thread.join(timeout=10.0)
        rc = encoder.wait()

    stderr_bytes = b"".join(stderr_chunks)
    if rc != 0 or frames_written == 0:
        err_msg = stderr_bytes.decode("utf-8", errors="replace")[-1200:]
        raise RuntimeError(
            f"ffmpeg H.264 encode failed (rc={rc}, frames={frames_written}): {err_msg}"
        )

    return {
        "input": str(input_path),
        "events": str(events_path),
        "output": str(output_path),
        "width": out_w,
        "height": out_h,
        "fps": round(meta.fps, 4),
        "frames_written": frames_written,
        "events_loaded": len(events),
        "events_in_window": len(tracker.events),
        "timeline_start_ts_ms": tl_start,
        "timeline_end_ts_ms": tl_end,
        "timeline_source": tl_source,
        "final_turn": tracker.turn_num,
        "final_tick": tracker.tick_num,
    }


def build_arg_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="python3 -m swarm.overlay.compositor",
        description="Off-display turn-queue strip & per-agent cursor video compositor.",
    )
    p.add_argument("--input", "-i", required=True, type=Path, help="Input raw MP4 file path")
    p.add_argument("--events", "-e", required=True, type=Path, help="Broker events.jsonl path")
    p.add_argument("--output", "-o", required=True, type=Path, help="Composed H.264 MP4 output path")
    p.add_argument("--start-ts-ms", type=int, default=None, help="Explicit video start epoch ms")
    p.add_argument("--end-ts-ms", type=int, default=None, help="Explicit video end epoch ms")
    p.add_argument("--sidecar", type=Path, default=None, help="Optional recording metadata JSON")
    p.add_argument(
        "--timeline-mode",
        choices=("auto", "wallclock", "span"),
        default="auto",
        help="Timeline alignment strategy (default: auto)",
    )
    p.add_argument(
        "--lerp-ms",
        type=float,
        default=DEFAULT_LERP_MS,
        help="Cursor smoothstep interpolation duration in video ms (default: 250)",
    )
    p.add_argument("--crf", type=int, default=20, help="H.264 CRF quality (default: 20)")
    p.add_argument("--preset", type=str, default="veryfast", help="libx264 preset (default: veryfast)")
    p.add_argument("--strict", action="store_true", help="Fail on unknown or non-v1 JSONL records")
    p.add_argument("--summary-json", type=Path, default=None, help="Write composition receipt JSON")
    return p


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = build_arg_parser()
    args = parser.parse_args(argv)
    summary = compose_video(
        input_path=args.input,
        events_path=args.events,
        output_path=args.output,
        start_ts_ms=args.start_ts_ms,
        end_ts_ms=args.end_ts_ms,
        sidecar_path=args.sidecar,
        timeline_mode=args.timeline_mode,
        lerp_ms=args.lerp_ms,
        crf=args.crf,
        preset=args.preset,
        strict=args.strict,
    )
    if args.summary_json is not None:
        args.summary_json.parent.mkdir(parents=True, exist_ok=True)
        args.summary_json.write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(summary))
    return 0


if __name__ == "__main__":
    sys.exit(main())
